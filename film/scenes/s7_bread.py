def _pulse(t, t0, up=0.12, down=0.35):
    """0 -> 1 -> 0: a quick accent at t0."""
    if t < t0 or t > t0 + up + down:
        return 0.0
    if t < t0 + up:
        return core.inout_sine((t - t0) / up)
    return 1.0 - core.inout_sine((t - t0 - up) / down)


def _bump(t, t0, dur):
    u = (t - t0) / dur
    return math.sin(math.pi * u) if 0.0 < u < 1.0 else 0.0


def _blink_at(t, times, dur=0.18):
    best = 0.0
    for tb in times:
        u = (t - tb) / dur
        if 0.0 <= u <= 1.0:
            best = max(best, core.smooth(u / 0.35) if u < 0.35 else 1.0 if u < 0.45 else 1.0 - core.smooth((u - 0.45) / 0.55))
    return best


def _track(t, keys, ease="inout_sine"):
    return core.track(t, keys, ease)


def _unit(v):
    n = math.hypot(v[0], v[1]) or 1.0
    return (v[0] / n, v[1] / n)


def _w2b(wx, wy, ax, ay, k, yaw, elev, depth):
    """A world point -> a rig's body space (anchor (ax, ay), drawn scale k, yaw, elev) at a camera
    depth `depth` (body units, + toward the camera): the inverse of base.Proj."""
    lx, ly = (wx - ax) / k, (wy - ay) / k
    c, s = math.cos(yaw), math.sin(yaw)
    return (lx * c - depth * s, (ly - depth * math.sin(elev)) / math.cos(elev), lx * s + depth * c)


