def _solve_target(key, who, t, measure, want, iters=8, z=None):
    """Damped fixed-point steps on the world target _STATE[key] so that measure(rig) lands on
    want; keeps the best target found (an unreachable want just gets as close as it can)."""
    if z is not None:
        _STATE[key + "_z"] = z
    best = None
    for _ in range(iters):
        got = measure(_scratch_draw(who, t))
        if got is None:
            break
        ex, ey = want[0] - got[0], want[1] - got[1]
        err = math.hypot(ex, ey)
        if best is None or err < best[0]:
            best = (err, _STATE[key])
        if err < 0.15:
            break
        p = _STATE[key]
        k = 0.9 * min(1.0, 20.0 / err)
        _STATE[key] = (p[0] + ex * k, p[1] + ey * k)
    if best is None:
        return None
    _STATE[key] = best[1]
    return round(best[0], 2)


def _solve_pat(key, t, want, want_ang, span=26.0, n=9, which="far"):
    """Grid-search the gnome's wrist target _STATE[key] (world px) so her hand lies ON `want`
    (the middle of the hand: grip and fingertips averaged) at about `want_ang` (the direction
    her fingers point) -- a tiny hand laid on a huge one reads by where and how it lies, and her
    short arm folds unpredictably near her body, so search instead of guessing."""
    best = None
    c0 = _STATE[key]
    for rnd in range(2):
        for i in range(n):
            for j in range(n):
                p = (c0[0] + span * (i / (n - 1) - 0.5) * 2.0, c0[1] + span * (j / (n - 1) - 0.5) * 2.0)
                _STATE[key] = p
                r = _scratch_draw("gnome", t)
                h = r.hand_far if which == "far" else r.hand_near
                tips = h.tips or [(h.x, h.y)]
                mx = 0.5 * (h.x + sum(q[0] for q in tips) / len(tips))
                my = 0.5 * (h.y + sum(q[1] for q in tips) / len(tips))
                da = math.atan2(math.sin(h.angle - want_ang), math.cos(h.angle - want_ang))
                cost = math.hypot(mx - want[0], my - want[1]) + 9.0 * abs(da)
                if best is None or cost < best[0]:
                    best = (cost, p)
        c0 = best[1]
        span *= 0.3
    _STATE[key] = best[1]
    return round(best[0], 2)


