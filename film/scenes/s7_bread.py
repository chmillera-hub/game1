def lantern_k(t, x, y):
    """0..1: how much of the lantern's warm key reaches a point (full near the lamp, falling
    off across the pool's reach -- which widens with each arrival: the warmth spreads)."""
    lv = lantern_lit(t)
    if lv <= 0.0:
        return 0.0
    d = math.hypot(x - core.lerp(_LAMP[0] + POOL_DX, pool_center(t), 0.5), (y - _LAMP[1]) * 0.55)
    R = lantern_reach(t)
    return lv * (1.0 - core.smoothstep(R * 0.45, R * 1.15, d))


def sky_light(t):
    """The world's light (no lantern): S6's warmed dusk -> golden -> blue hour; the evening
    darkens a little as it goes (the lamp is the light that matters by the end)."""
    L = G.light_for(tod(t))
    b = blue(t)
    if b > 0.0:
        L = L.with_(exposure=L.exposure * (1.0 - 0.2 * b))
    return L


def lamp_light(t, x, y, base, strength=1.0):
    """base lit by the lantern at world (x, y): an amber key from the lamp's direction, a cool
    sky rim from the other side (Klaus-style), by how much of its light reaches there; the
    lamp matters more the darker the sky (dusk 55 % .. blue hour 100 %)."""
    k = lantern_k(t, x, y) * strength * (0.62 + 0.38 * blue(t))
    if k <= 0.0:
        return base
    dx, dy = _LAMP[0] - x, _LAMP[1] - y
    d = _unit((dx, dy))
    side = 1.0 if dx >= 0 else -1.0
    Ll = ch.Light(key=LAMP_KEY, ambient=LAMP_AMB, rim=SKY_RIM, rim_strength=0.6, direction=d,
                  rim_direction=(-0.72 * side, -0.69), exposure=LAMP_EXPOSURE, name="s7_lamp")
    return ch.Light.lerp(base, Ll, core.clamp(k))


def first_light(t):
    """C3: 0..1 -- the lantern's first light landing on the dragon's upturned face."""
    return _r(t, T_LIGHT, T_LIGHT + 0.5) * (1.0 - _r(t, CUT_C4 - 0.01, CUT_C4))


def cast_light(t, x, y, who=None):
    """The light on a cast member at world (x, y): the sky light, the warm rims between the two
    leads (S6 continuity, fading through the bread), and the lantern's warm key from the upper
    right with a cool sky rim from the other side (the Klaus-like two-light look)."""
    L = sky_light(t)
    if who in ("gnome", "dragon"):
        w = 1.0 - _r(t, 3.2, 7.0)
        if w > 0.0:
            side = 1.0 if who == "gnome" else -1.0
            rd0 = L.rim_dir()
            rd = _unit((core.lerp(rd0[0], side * 0.96, w), core.lerp(rd0[1], -0.29, w)))
            L = L.with_(rim=core.lerp_tuple(L.rim, WARM_RIM, w), rim_strength=core.lerp(L.rim_strength, 1.0, w),
                        rim_direction=rd, exposure=L.exposure * (1.0 + 0.05 * w))
    L = lamp_light(t, x, y, L, 0.95)
    k = first_light(t) if who in ("dragon", "faun", "gnome") else 0.0
    if k > 0.0:
        d = _unit((_LAMP[0] - x, _LAMP[1] - y))
        L = L.with_(rim=core.lerp_tuple(L.rim, (1.0, 0.7, 0.36), k), rim_direction=d,
                    rim_strength=core.lerp(L.rim_strength, 1.25, k), exposure=L.exposure * (1.0 + 0.1 * k))
    return L


def set_light(t, x=None, y=None, dim=1.0):
    """Light for props and set pieces (the bench, bread lying about): the sky + the lantern."""
    L = sky_light(t)
    if x is not None:
        L = lamp_light(t, x, y, L, 0.75)
    return L.with_(exposure=L.exposure * dim) if dim != 1.0 else L


