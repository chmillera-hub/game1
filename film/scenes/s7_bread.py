def _all_hops():
    """(start, duration, du, height) of every little hop she makes along the seat."""
    da, dc = (U_GNOME_A - U_GNOME) / len(G_SCOOT), (U_GNOME2 - U_GNOME_A) / len(G_HOPS)
    return [(t0, d, da, 0.7) for t0, d in G_SCOOT] + [(t0, d, dc, 1.0) for t0, d in G_HOPS]


def gnome_seat(t):
    """Her place on bench 1 (fraction u) and the height (0..1) of her little hops: two toward
    him as she hands him his half (A), two more over beside him to make room for the faun (C)."""
    seat, hop = U_GNOME, 0.0
    for t0, d, du, hk in _all_hops():
        u = core.clamp((t - t0) / d)
        seat += du * core.inout_sine(u)
        hop = max(hop, hk * math.sin(math.pi * u) if 0.0 < u < 1.0 else 0.0)
    return seat, hop


def seat_dip(u, t=None, height=None):
    """World px a point on bench 1 at u sinks under the dragon's weight (S6's lasting sag)."""
    return _STATE["garden"].seat_dip(u, bench_sag(t), sag_u=U_DRAGON, height=height)


def bench_sag(t):
    """S6's sag under him, rocked a little as the faun sits and as she hops over."""
    if t is None:
        return SAG
    s = SAG + 0.14 * B.wobble(t, T_F_SIT1 - 0.06, 3.2, 4.4) / 1.35
    for h0, hd, _du, hk in _all_hops():
        s += 0.05 * hk * B.wobble(t, h0 + hd, 3.4, 5.0) / 1.35
    return s


