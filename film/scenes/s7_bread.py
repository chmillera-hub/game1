def _pool(lc, x, y, r, squash, color, alpha):
    """A broad, even pool of light on the ground (S8's profile), into the light layer."""
    if r <= 0.0 or alpha <= 0.0:
        return
    c = core.col(color)
    lc.save()
    lc.translate(x, y)
    lc.scale(1.0, squash)
    pat = cairo.RadialGradient(0, 0, 0, 0, 0, r)
    for off, a in _POOL_PROFILE:
        pat.add_color_stop_rgba(off, c[0], c[1], c[2], a * alpha)
    lc.set_operator(cairo.OPERATOR_ADD)
    lc.set_source(pat)
    lc.arc(0, 0, r, 0, math.tau)
    lc.fill()
    lc.restore()


def _redraw_clipped(cr, draw_fn, x, y, r):
    cr.save()
    cr.new_path()
    cr.arc(x, y, r, 0.0, math.tau)
    cr.clip()
    draw_fn()
    cr.restore()


