def lantern_lit(t):
    """The lantern: dark until the ember reaches it, then it CATCHES (a sputter, a flare) and
    settles, and grows brighter with each newcomer: courier -> worker -> the dragged bench."""
    if t < T_LIGHT:
        return 0.0
    u = min(1.0, (t - T_LIGHT) / 0.55)
    catch = 0.7 * core.out_cubic(u) * (1.0 - 0.4 * math.sin(u * math.pi * 3.0) ** 2)
    lv = catch + 0.1 * _r(t, T_LIGHT + 0.4, T_LIGHT + 1.2) + 0.08 * _r(t, T_F_GIVE - 0.1, T_F_GIVE + 0.6)
    lv += 0.06 * _r(t, B_WORKER.t, B_FULL.t) + 0.1 * _r(t, T_DRAG0, T_DRAG1)
    return min(1.0, lv)


def lantern_reach(t):
    """The radius (world px) of the lantern's warm pool: it widens with each arrival."""
    return _track(t, [(T_LIGHT, 220.0), (T_LIGHT + 0.5, 470.0), (T_F_GIVE, 480.0), (T_F_GIVE + 0.8, 560.0),
                      (B_WORKER.t, 550.0), (B_FULL.t, 610.0), (T_DRAG0, 630.0), (T_DRAG1 + 0.4, 840.0)])


