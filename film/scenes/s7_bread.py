def umpire_state(t):
    """The S6 umpire: on the crest board (u 0.5) as S6 left him; startled as she scoots along the
    seat under him, he takes off up and away (A2); he flies back down onto the crest board (u
    UMPIRE_U2, S8's place) as the three pigeons hop up into the seat's last gap (D). Returns
    (x, y, PigeonPose) or None while he is away."""
    seed = 101
    x0, y0 = _crest_point(0.5)
    x1, y1 = _crest_point(UMPIRE_U2)
    puff = 0.25 * max(0.0, core.noise1(t * 0.3, seed + 5))
    if t < T_UMP_OFF:
        look = None
        nod = core.noise1(t * 0.6 + 3.0, seed)
        if abs(nod) > 0.45:
            look = -1.0 * (1.0 - 1.1 * core.smooth((abs(nod) - 0.45) / 0.2))
        if T_SNAP < t:                                   # the bread below catches his eye
            look = core.lerp(-1.0, 0.0, _r(t, T_SNAP, T_SNAP + 0.3))
        tilt = 0.15 * _win(t, T_SNAP, CUT_B, 0.2, 0.2)
        return x0, y0, ch.PigeonPose(facing=-1, look=look, tilt=tilt, puff=puff, seed=seed)
    if t < T_UMP_OFF + UMP_FLY:                          # a startled take-off, up and away to the left
        u = (t - T_UMP_OFF) / UMP_FLY
        x = core.lerp(x0, UMP_AWAY[0], core.in_quad(u))
        y = core.lerp(y0, UMP_AWAY[1], core.inout_sine(u))
        return x, y, ch.PigeonPose(facing=-1, fly=core.clamp(u * 3.0), flap=1.0 - core.clamp(u * 3.0), seed=seed)
    if t < T_UMP_UP - UMP_FLY:
        return None
    if t < T_UMP_UP:                                     # gliding back in from above, wings out, to land
        u = (t - (T_UMP_UP - UMP_FLY)) / UMP_FLY
        x = core.lerp(UMP_AWAY[0] + 260.0, x1, core.out_quad(u))
        y = core.lerp(UMP_AWAY[1] - 40.0, y1, core.out_quad(u))
        fl = core.clamp((1.0 - u) * 3.0)
        return x, y, ch.PigeonPose(facing=1, fly=fl, flap=1.0 - fl, seed=seed)
    look = None
    nod = core.noise1(t * 0.6 + 3.0, seed)
    if abs(nod) > 0.45:
        look = -1.0 * (1.0 - 1.1 * core.smooth((abs(nod) - 0.45) / 0.2))
    sl = _seat_look(t, 3)
    if sl is not None:
        look = sl
    land = 0.5 * (1.0 - _r(t, T_UMP_UP, T_UMP_UP + 0.3))
    p = ch.PigeonPose(facing=-1, look=look, flap=land, blink=_blink_at(t, [B_FULL.t + 0.32]) or None, puff=puff, seed=seed)
    return x1, y1, p


