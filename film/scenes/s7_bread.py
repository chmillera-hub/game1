_LUTS = {}


def _warm_grade(cr, t):
    """S6's warm curve (its last frame), relaxing as the real golden hour takes over."""
    k = round(core.clamp(1.0 - _r(t, 0.3, 4.5)) * 20.0) / 20.0
    if k <= 0.0:
        return
    if k not in _LUTS:
        _LUTS[k] = fx.make_lut(r=lambda x, k=k: x + 0.04 * k * math.sin(math.pi * x),
                               g=lambda x, k=k: x + 0.012 * k * math.sin(math.pi * x),
                               b=lambda x, k=k: x - 0.028 * k * math.sin(math.pi * x))
    fx.grade_lut(cr, _LUTS[k])


def _post_kw(t, lit):
    out = {}
    for k, w in G.blend(tod(t)):
        for a, v in G.POST[k].items():
            if isinstance(v, tuple):
                o = out.get(a, (0.0, 0.0, 0.0))
                out[a] = tuple(o[i] + w * v[i] for i in range(3))
            else:
                out[a] = out.get(a, 0.0) + w * v
    out["bloom_strength"] = out["bloom_strength"] + 0.1 * lit
    return out


def _golden_w(t):
    """How much of the sun is left (for shadows and the last-light key)."""
    return 1.0 - blue(t)


def _redraw_clipped(cr, draw_fn, x, y, r):
    cr.save()
    cr.new_path()
    cr.arc(x, y, r, 0.0, math.tau)
    cr.clip()
    draw_fn()
    cr.restore()


