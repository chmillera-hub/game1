def faun_walk_x(t):
    dec = T_F_STOP - T_F_NOTICE
    xn = F_STOP[0] - 0.5 * F_SPEED * dec
    if t < T_F_NOTICE:
        return xn - F_SPEED * (T_F_NOTICE - t)
    if t < T_F_STOP:
        u = T_F_STOP - t
        return F_STOP[0] - 0.5 * F_SPEED * u * u / dec
    return F_STOP[0]


