class Flock:
    """Ground pigeons with explicit starting places (S6's last frame), arrivals that fly in,
    crumbs claimed first come first served, and forced events (a walk to a spot, a flap-hop up
    onto the bench seat, a flutter away from the dragged bench). Segments:
    (t0, t1, kind, xa, ya, xb, yb, facing). A pure function of t once built (setup)."""

    def __init__(self, starts, crumbs, arrivals, x_range, y_range, seed=7, t_end=31.0, forced=None, speed=55.0):
        import heapq
        import random
        self.crumbs = [{"x": c[0], "t": c[1], "y": c[2], "by": None, "eaten": None} for c in crumbs]
        self.birds = []
        forced = forced or {}
        for i, (x, y, f) in enumerate(starts):
            self.birds.append({"x": x, "y": y, "f": f, "segs": [], "seed": seed * 31 + i, "arrive": None,
                               "forced": sorted(forced.get(i, [])), "done": False, "xr": x_range, "yr": y_range})
        for j, arr in enumerate(arrivals):
            ta, side = arr[0], arr[1]
            i = len(starts) + j
            r = random.Random(seed * 131 + i)
            if len(arr) > 2:
                lx, ly = arr[2]
                xr = (lx - 70.0, lx + 70.0)
                yr = (ly - 8.0, ly + 8.0)
            else:
                lx = r.uniform(x_range[0] + 60.0, x_range[1] - 60.0)
                ly = r.uniform(*y_range)
                xr, yr = x_range, y_range
            sx = lx - 640.0 if side < 0 else lx + 640.0
            f = 1 if lx > sx else -1
            dur = 1.15 + 0.3 * r.random()
            b = {"x": lx, "y": ly, "f": f, "seed": seed * 31 + i, "arrive": ta, "forced": sorted(forced.get(i, [])),
                 "segs": [(ta, ta + dur, "fly", sx, ly - 420.0, lx, ly, f), (ta + dur, ta + dur + 0.45, "land", lx, ly, lx, ly, f)],
                 "done": False, "xr": xr, "yr": yr}
            b["t_free"] = ta + dur + 0.45
            self.birds.append(b)
        self.speed = speed
        heap = []
        for i, b in enumerate(self.birds):
            heapq.heappush(heap, (b.get("t_free", 0.0), i))
        while heap:
            tt, i = heapq.heappop(heap)
            b = self.birds[i]
            if tt >= t_end or b["done"]:
                continue
            r = random.Random(b["seed"] * 7919 + int(tt * 100))
            nt = self._decide(b, tt, r)
            heapq.heappush(heap, (nt, i))
        for b in self.birds:
            b["t0s"] = [s[0] for s in b["segs"]]

    def _forced_now(self, b, tt, horizon):
        if b["forced"] and b["forced"][0][0] <= tt + horizon:
            return b["forced"][0]
        return None

    def _decide(self, b, tt, r):
        x, y, f = b["x"], b["y"], b["f"]
        ev = self._forced_now(b, tt, 0.6)
        if ev is not None:
            te, kind, prm = ev
            if te > tt + 0.02:
                b["segs"].append((tt, te, "idle", x, y, x, y, f))
                return te
            b["forced"].pop(0)
            if kind == "goto":                          # walk to a spot (then the next event)
                tx, ty = prm
                f = 1 if tx >= x else -1
                dur = max(0.25, (abs(tx - x) + abs(ty - y)) / self.speed)
                b["segs"].append((tt, tt + dur, "walk", x, y, tx, ty, f))
                b.update(x=tx, y=ty, f=f)
                return tt + dur
            if kind == "hop_to":                        # a flap-hop up to (tx, ty) (the bench seat), then stay
                tx, ty, ff = prm
                b["segs"].append((tt, tt + 0.5, "flaphop", x, y, tx, ty, ff))
                b["segs"].append((tt + 0.5, 99.0, "perch", tx, ty, tx, ty, ff))
                b.update(x=tx, y=ty, f=ff, done=True)
                return 99.0
            if kind == "flee":                          # flutter away from danger, land somewhere safe
                tx, ty = prm
                ff = 1 if tx >= x else -1
                b["segs"].append((tt, tt + 0.9, "flyto", x, y, tx, ty, ff))
                b.update(x=tx, y=ty, f=ff, xr=(tx - 10.0, tx + 10.0), yr=(ty - 2.0, ty + 2.0))
                return tt + 0.9
        best = None
        for c in self.crumbs:
            if c["by"] is None and c["t"] <= tt + 0.5:
                d = abs(c["x"] - x) + 2.0 * abs(c["y"] - y)
                if d < 420.0 and (best is None or d < best[0]):
                    best = (d, c)
        if best is not None:
            c = best[1]
            c["by"] = id(b)
            f = 1 if c["x"] >= x else -1
            tx = c["x"] - f * 22.0 * SC
            dist = abs(tx - x) + abs(c["y"] - y)
            dur = max(0.25, dist / self.speed)
            b["segs"].append((tt, tt + dur, "walk", x, y, tx, c["y"], f))
            npk = 2 + r.randint(0, 2)
            t1 = tt + dur + npk * 0.42
            b["segs"].append((tt + dur, t1, "peck", tx, c["y"], tx, c["y"], f))
            c["eaten"] = t1 - 0.1
            b.update(x=tx, y=c["y"], f=f)
            return t1
        xr, yr = b["xr"], b["yr"]
        k = r.random()
        if k < 0.38:
            dur = r.uniform(0.9, 2.4)
            if r.random() < 0.25:
                f = -f
            b["segs"].append((tt, tt + dur, "idle", x, y, x, y, f))
        elif k < 0.66:
            dx = r.uniform(18.0, 60.0) * (1 if r.random() < 0.5 else -1)
            tx = core.clamp(x + dx, *xr)
            ty = core.clamp(y + r.uniform(-7.0, 7.0), *yr)
            f = 1 if tx >= x else -1
            dur = max(0.3, (abs(tx - x) + abs(ty - y)) / self.speed)
            b["segs"].append((tt, tt + dur, "walk", x, y, tx, ty, f))
            x, y = tx, ty
        elif k < 0.93:
            dur = r.choice((1, 2, 3)) * 0.42
            b["segs"].append((tt, tt + dur, "peck", x, y, x, y, f))
        else:
            tx = core.clamp(x + f * 8.0, *xr)
            b["segs"].append((tt, tt + 0.42, "hop", x, y, tx, y, f))
            x = tx
            dur = 0.42
        b.update(x=x, y=y, f=f)
        return tt + dur

    def crumb_eaten(self, k, t):
        e = self.crumbs[k]["eaten"] if k < len(self.crumbs) else None
        return e is not None and t >= e

    def position(self, i, t):
        """(x, y) of bird i at t (no pose): for picking who hops up onto the seat."""
        b = self.birds[i]
        segs = b["segs"]
        if not segs or t < segs[0][0]:
            return (b["x"], b["y"]) if not segs else (segs[0][3], segs[0][4])
        import bisect
        j = bisect.bisect_right(b["t0s"], t) - 1
        t0, t1, kind, xa, ya, xb, yb, f = segs[j]
        u = core.clamp((t - t0) / max(1e-6, t1 - t0))
        return core.lerp(xa, xb, u), core.lerp(ya, yb, u)

    def states(self, t):
        """[(x, y, PigeonPose, perched, bird index)] for every bird present at t."""
        import bisect
        out = []
        for i, b in enumerate(self.birds):
            segs = b["segs"]
            if not segs or t < segs[0][0]:
                if b["arrive"] is not None:
                    continue
                if not segs:
                    out.append((b["x"], b["y"], ch.PigeonPose(facing=b["f"], seed=b["seed"]), False, i))
                    continue
                s = segs[0]
                out.append((s[3], s[4], ch.PigeonPose(facing=s[7], seed=b["seed"]), False, i))
                continue
            j = bisect.bisect_right(b["t0s"], t) - 1
            t0, t1, kind, xa, ya, xb, yb, f = segs[j]
            u = core.clamp((t - t0) / max(1e-6, t1 - t0)) if t <= t1 else 1.0
            if t > t1 and kind not in ("perch",):
                kind, xa, ya = "idle", xb, yb
            seed = b["seed"]
            perched = kind == "perch"
            if kind == "walk":
                x, y = core.lerp(xa, xb, u), core.lerp(ya, yb, u)
                p = ch.PigeonPose(facing=f, walk=1.0, phase=(abs(x - xa) + abs(y - ya)) / max(1e-6, ch.pigeon_stride(SC)), seed=seed)
            elif kind == "peck":
                x, y = xa, ya
                p = ch.PigeonPose(facing=f, peck=((t - t0) / 0.42) % 1.0, seed=seed)
            elif kind == "hop":
                x, y = core.lerp(xa, xb, u), ya
                p = ch.PigeonPose(facing=f, hop=u, seed=seed)
            elif kind == "fly":
                e = core.out_quad(u)
                x, y = core.lerp(xa, xb, e), yb
                lift = (yb - ya) * (1.0 - e) ** 1.4 + 30.0 * math.sin(math.pi * e) * (1.0 - e)
                p = ch.PigeonPose(facing=f, fly=1.0, lift=lift / SC, seed=seed)
            elif kind == "land":
                x, y = xb, yb
                p = ch.PigeonPose(facing=f, flap=1.0 - u, lift=4.0 * (1.0 - u), seed=seed)
            elif kind in ("flaphop", "flyto"):
                e = core.smooth(u)
                x, y = core.lerp(xa, xb, e), core.lerp(ya, yb, e)
                hgt = (26.0 if kind == "flaphop" else 60.0) * math.sin(math.pi * u)
                p = ch.PigeonPose(facing=f, flap=math.sin(math.pi * u) ** 0.5, lift=hgt / SC, seed=seed)
            elif kind == "perch":
                x, y = xa, ya
                pk = core.noise1(t * 0.5 + seed, seed)
                p = ch.PigeonPose(facing=f, peck=((t * 1.1 + seed) % 1.0) if pk > 0.55 else 0.0,
                                  puff=0.3 * max(0.0, core.noise1(t * 0.3, seed + 5)), seed=seed)
            else:
                x, y = xa, ya
                nod = core.noise1((t + seed * 1.37) * 0.6, seed)
                look = f * (1.0 - 1.1 * core.smooth((abs(nod) - 0.45) / 0.2)) if abs(nod) > 0.45 else None
                p = ch.PigeonPose(facing=f, look=look, puff=0.3 * max(0.0, core.noise1(t * 0.3, seed + 5)), seed=seed)
            out.append((x, y, p, perched, i))
        return out


