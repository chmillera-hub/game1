def _bread_detail(cr):
    ux, uy = cr.user_to_device_distance(1.0, 0.0)
    dev = math.hypot(ux, uy)
    return 2 if dev >= 0.9 else 1 if dev >= 0.55 else 0


def _dev_scale(cr):
    ux, uy = cr.user_to_device_distance(1.0, 0.0)
    return math.hypot(ux, uy)


_INSERT = {"on": False}          # A3 (the hands insert) is being drawn: the close-up loaf


def _bread(cr, x, y, size, light, state, face, seed, crack=0.0):
    """Her bread. In the close insert (A3) a torn half is drawn as the props loaf -- the rig's
    half reads like a shell at that size -- with its fluffy torn face toward `face` and warm
    from the oven; everywhere else (and at every other size) the gnome's own bread."""
    if _INSERT["on"] and state == "half":
        P.draw_bread(cr, x, y, size * 0.94, light, 0.0, state="half", face=face, seed=seed)
        return
    ch.gnome_bread(cr, x, y, size, light, state, face=face, seed=seed, detail=_bread_detail(cr), crack=crack)


def bread_giver(state, face, size, light, seed=3, ofs=None, cap=None):
    """A hold callback: bread held upright at a library-like offset from the grip. cap: record
    its device centre and drawn scale in _CAP[cap] (setup reads them to solve the receiver)."""
    def cb(cr, f):
        cr.save()
        cr.rotate(-f.angle)
        if ofs is not None:
            a, b = ofs
        elif state == "piece":
            a, b = face * 3.0, -3.0
        elif state == "half":
            a, b = face * size * 0.16, -size * 0.12
        else:
            a, b = face * size * 0.3, -size * 0.18
        if cap:
            _CAP[cap] = (*cr.user_to_device(a, b), _dev_scale(cr))
        _bread(cr, a, b, size, light, state, face, seed)
        cr.restore()
    return cb


def bread_receiver(key, state, face, size, light, seed=3, cap=None, upright=True, scale=1.0, hang=False, crack=0.0):
    """A hold callback for the receiver of hand-off `key`: draws the bread exactly where (and
    as big as) the giver drew it at the hand-off instant (offset, angle and scale solved once in
    setup from _MEAS[key]), riding with this hand from then on. hang=True keeps the offset
    gravity-aligned (a loaf carried in a turning hand stays below/beside it instead of swinging
    round the grip with the hand)."""
    def cb(cr, f):
        o = _HOLD.get(key)
        if o is None:
            w = _MEAS.get(key)
            if w is None:
                return
            ox, oy = cr.device_to_user(w[0], w[1])
            o = _HOLD[key] = (ox, oy, f.angle, w[2] / max(1e-6, _dev_scale(cr)))
        cr.save()
        if hang:
            # the solved offset, expressed upright (at the solve the hand's angle was o[2])
            c, s = math.cos(o[2]), math.sin(o[2])
            cr.rotate(-f.angle)
            cr.translate(o[0] * c - o[1] * s, o[0] * s + o[1] * c)
        else:
            cr.translate(o[0], o[1])
            cr.rotate(-f.angle if upright else -o[2])
        k = o[3] * scale
        if k != 1.0:
            cr.scale(k, k)
        if cap:
            _CAP[cap] = (*cr.user_to_device(0.0, 0.0), _dev_scale(cr))
        _bread(cr, 0.0, 0.0, size, light, state, face, seed, crack=crack)
        cr.restore()
    return cb


def _loaf_up(light, t=None):
    """The whole loaf in her near hand as it comes out of the satchel (solved so that it lands
    exactly where tear_bread draws it at phase 0). As she grabs it, it starts exactly where the
    satchel's own (smaller, peeking) loaf was -- rising out of the bag's mouth (clipped there)
    and growing into her grip as she lifts it: no frame where it pops."""
    base = bread_receiver("loaf", "loaf", 1.0, LOAF, light, seed=0, cap="loaf_up", hang=True)
    if t is None or "loaf_sat" not in _STATE or "cam_m" not in _STATE:
        return base
    k = core.inout_sine(core.clamp((t - T_GRAB) / (T_TEAR0 - 0.1 - T_GRAB)))
    if k >= 1.0:
        return base

    def cb(cr, f):
        o = _HOLD.get("loaf")
        if o is None:
            base(cr, f)
            return
        # where (device) and how big (device px per bread unit) the solved hold draws it ...
        cr.save()
        c_, s_ = math.cos(o[2]), math.sin(o[2])
        cr.rotate(-f.angle)
        cr.translate(o[0] * c_ - o[1] * s_, o[0] * s_ + o[1] * c_)
        d1 = cr.user_to_device(0.0, 0.0)
        s1 = _dev_scale(cr) * o[3]
        cr.restore()
        # ... and the satchel's peeking loaf (size 30 body units at the bag's mouth)
        m = _STATE["cam_m"]
        d0 = m.transform_point(*_STATE["loaf_sat"])
        z = math.hypot(*m.transform_distance(1.0, 0.0))
        s0 = z * SC * 30.0 / LOAF
        mouth_y = d0[1] + 1.5 * SC * z
        cx, cy = core.lerp(d0[0], d1[0], k), core.lerp(d0[1], d1[1], k)
        sk = core.lerp(s0, s1, k)
        cr.save()
        cr.identity_matrix()
        masked = k < 0.6                             # still coming out of the bag: fade at its mouth
        if masked:
            r = LOAF * 0.62 * sk
            cr.rectangle(cx - r, cy - r, 2.0 * r, 2.0 * r)
            cr.clip()
            cr.push_group()
        cr.translate(cx, cy)
        cr.scale(sk, sk)
        _CAP["loaf_up"] = (*cr.user_to_device(0.0, 0.0), _dev_scale(cr))
        _bread(cr, 0.0, 0.0, LOAF, light, "loaf", 1.0, 0)
        if masked:
            cr.identity_matrix()
            cr.pop_group_to_source()
            edge = mouth_y + 30.0 * SC * z * core.smooth(k / 0.6)
            feather = 3.5 * SC * z
            g = cairo.LinearGradient(0.0, edge - feather, 0.0, edge + feather)
            g.add_color_stop_rgba(0.0, 0, 0, 0, 1.0)
            g.add_color_stop_rgba(1.0, 0, 0, 0, 0.0)
            cr.mask(g)
        cr.restore()
    return cb


