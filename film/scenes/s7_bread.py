def _pan_of(x_world, t):
    _name, cam = camera(t)
    sx, _sy = cam.to_screen(x_world, 900.0)
    return round(core.clamp((sx - 960.0) / 960.0, -1.0, 1.0), 2)


def _steps(t0, t1, x_of, stride, every=0.5):
    """Footfall times: one per half walk cycle between t0 and t1 (x_of(t) = distance walked)."""
    out = []
    last = None
    t = t0
    while t < t1:
        k = int(x_of(t) / max(1e-6, stride) * 2.0)
        if last is not None and k != last:
            out.append(t)
        last = k
        t += 1.0 / 48.0
    return out


