def lantern_lit(t):
    """The lantern: dark until the ember reaches it as the faun sits, then it catches (a sputter
    up) and grows brighter with each newcomer: courier -> worker -> the dragged bench."""
    if t < T_LIGHT:
        return 0.0
    u = min(1.0, (t - T_LIGHT) / 0.55)
    catch = 0.62 * core.out_cubic(u) * (1.0 - 0.35 * math.sin(u * math.pi * 3.0) ** 2)
    lv = catch + 0.12 * _r(t, T_F_GIVE - 0.1, T_F_GIVE + 0.6) + 0.1 * _r(t, B_WORKER.t, B_FULL.t)
    lv += 0.16 * _r(t, T_DRAG0, T_DRAG1)
    return min(1.0, lv)


def lantern_reach(t):
    """The radius (world px) of the lantern's warm pool: it widens with each arrival."""
    return _track(t, [(T_LIGHT, 120.0), (T_LIGHT + 0.6, 380.0), (T_F_GIVE, 420.0), (T_F_GIVE + 0.8, 520.0),
                      (B_WORKER.t, 530.0), (B_FULL.t, 600.0), (T_DRAG0, 620.0), (T_DRAG1 + 0.4, 820.0)])


_LAMP = [1252.7, 446.2]                      # the lantern's centre (setup measures it)
