    c.paint()
    buf.flush()
    cr.save()
    cr.identity_matrix()
    cr.scale(4.0, 4.0)
    cr.set_source_surface(buf, 0, 0)
    cr.get_source().set_filter(cairo.FILTER_BILINEAR)
    cr.paint()
    cr.restore()


