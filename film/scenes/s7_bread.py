def _post_kw(t, lit):
    out = {}
    for k, w in G.blend(tod(t)):
        for a, v in G.POST[k].items():
            if isinstance(v, tuple):
                o = out.get(a, (0.0, 0.0, 0.0))
                out[a] = tuple(o[i] + w * v[i] for i in range(3))
            else:
                out[a] = out.get(a, 0.0) + w * v
    out["bloom_strength"] = out["bloom_strength"] + 0.1 * lit
    # quantised, so the cached vignette / bloom tables are reused from frame to frame
    q = {"vignette": 0.02, "grain": 0.005, "bloom_strength": 0.02, "threshold": 0.02, "bloom_radius": 0.1, "wide": 0.05}
    for a, step in q.items():
        if a in out:
            out[a] = round(round(out[a] / step) * step, 4)
    if "vignette_color" in out:
        out["vignette_color"] = tuple(round(v * 50.0) / 50.0 for v in out["vignette_color"])
    return out


