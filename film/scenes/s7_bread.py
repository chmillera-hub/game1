def _solve_target(key, who, t, measure, want, iters=5, z=None):
    """Fixed-point steps on the world target _STATE[key] so that measure(rig) lands on want."""
    if z is not None:
        _STATE[key + "_z"] = z
    err = None
    for _ in range(iters):
        rig = _scratch_draw(who, t)
        got = measure(rig)
        if got is None:
            break
        ex, ey = want[0] - got[0], want[1] - got[1]
        err = math.hypot(ex, ey)
        p = _STATE[key]
        _STATE[key] = (p[0] + ex, p[1] + ey)
        if err < 0.15:
            break
    return err


