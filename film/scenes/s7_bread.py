def sun(t):
    """0 golden .. 1 dusk .. 2 blue hour (from shot C on)."""
    if t < CUT_C:
        return 0.0
    name, _a, _b = _shot_span(t)
    keys = SUN_KEYS.get(name)
    return 2.0 if keys is None else _track(t, keys, "linear")


def tod(t):
    """The garden's time of day: S6's warmed dusk -> golden (the bread, the birds) -> dusk as
    the faun comes -> blue hour by the time the bench is full."""
    if t < CUT_C:
        return ("dusk", "golden", core.lerp(0.5, 1.0, core.smooth(t / T_GOLD))) if t < T_GOLD else "golden"
    s = sun(t)
    if s >= 2.0:
        return "blue_hour"
    return ("golden", "dusk", s) if s <= 1.0 else ("dusk", "blue_hour", s - 1.0)


def blue(t):
    """0..1: how far into blue hour."""
    k = tod(t)
    if isinstance(k, str):
        return 1.0 if k == "blue_hour" else 0.0
    return k[2] if k[1] == "blue_hour" else 0.0


def dusk_k(t):
    """0..1: how far the sun has gone (golden 0 -> dusk 1 -> blue hour 1)."""
    k = tod(t)
    if isinstance(k, str):
        return 0.0 if k == "golden" else 1.0
    if k[1] == "dusk":
        return k[2]
    return 1.0 if k[0] == "dusk" else 0.0


