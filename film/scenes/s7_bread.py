def drag_u(t):
    u = 0.0
    for a, b, d in HEAVES:
        u += d * core.inout_sine(core.clamp((t - a) / (b - a)))
    return min(1.0, u)


def heave_effort(t):
    """0..1: how hard he is pulling (peaks in each heave)."""
    e = 0.0
    for a, b, d in HEAVES:
        e = max(e, _win(t, a - 0.12, b, 0.15, 0.25))
    return e


def bench2_spot(t):
    return G.lerp_spot(BENCH2_START, G.BENCH2, drag_u(t))


def _bench_pt(sp, X, Y, Z):
    """A point on a bench (bench units at scale 1, its own frame) -> world."""
    px, py = B.Proj(sp.yaw, 0.12).xy((X, Y, Z))
    return sp.x + px * SC, sp.y + py * SC


def bench2_lift(t):
    """The dragged end of the second bench comes up off the turf a little on each heave (the
    bench pivots on its far feet): (angle rad, pivot world point)."""
    sp = bench2_spot(t)
    a = 0.0
    for h0, h1, _d in HEAVES:
        a = max(a, 0.032 * _win(t, h0 - 0.08, h1 + 0.05, 0.16, 0.22))
    px, py = _bench_pt(sp, sp.length / 2.0 - 16.0, 0.0, 0.0)
    return a, (px, py)


def _lifted(pt, a, pv):
    """pt rotated by a (rad, clockwise on screen) about pv."""
    if a == 0.0:
        return pt
    c, s = math.cos(a), math.sin(a)
    dx, dy = pt[0] - pv[0], pt[1] - pv[1]
    return pv[0] + dx * c - dy * s, pv[1] + dx * s + dy * c


def bench2_grip(t):
    """Where the dwarf holds the second bench: its left end, at the seat's front corner (lifted
    with the end on each heave)."""
    sp = bench2_spot(t)
    g = _bench_pt(sp, -(sp.length / 2.0 - 16.0) + 6.0, -P.BENCH_SEAT_H + 6.0, 30.0)
    a, pv = bench2_lift(t)
    return _lifted(g, a, pv)


