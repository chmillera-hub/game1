def _keys_at(t, keys):
    """[(t, spec, hand)] -> (spec_a, spec_b, u, hand): the hand's shape changes over the last part
    of each move (it closes as it arrives) -- a blend, never a one-frame switch."""
    if t <= keys[0][0]:
        return keys[0][1], keys[0][1], 0.0, keys[0][2]
    for (t0, a, ha), (t1, b_, hb) in zip(keys, keys[1:]):
        if t < t1:
            u = (t - t0) / max(1e-6, t1 - t0)
            return a, b_, u, _hand_mix(ha, hb, core.smooth(core.clamp((u - 0.45) / 0.55)))
    return keys[-1][1], keys[-1][1], 1.0, keys[-1][2]


