def _hand_mix(a, b, u):
    """A hand shape between two base.HAND_POSES (or blends): hands change shape over a few frames,
    never in one."""
    if u <= 0.0:
        return a
    if u >= 1.0:
        return b
    A_ = B.HAND_POSES[a] if isinstance(a, str) else a
    B_ = B.HAND_POSES[b] if isinstance(b, str) else b
    lp = core.lerp
    return {"curl": tuple(lp(x, y, u) for x, y in zip(A_["curl"], B_["curl"])), "spread": lp(A_["spread"], B_["spread"], u),
            "thumb": (lp(A_["thumb"][0], B_["thumb"][0], u), lp(A_["thumb"][1], B_["thumb"][1], u))}


def _hand_track(t, keys):
    """keys [(t, (dx, dy, dz) from his lap, hand shape, wrist turn[, ease])] -> (body target, hand
    shape, turn): eased between keys, the wrist on a small arc, the hand's shape blending with
    the move."""
    lap = _STATE["lap"]
    if t <= keys[0][0]:
        k = keys[0]
        return _v_add(lap, k[1]), k[2], k[3]
    for k0, k1 in zip(keys, keys[1:]):
        if t < k1[0]:
            e = k1[4] if len(k1) > 4 else "inout_sine"
            u = core.ease(e, (t - k0[0]) / max(1e-6, k1[0] - k0[0]))
            p = _v_lerp(k0[1], k1[1], u)
            d = math.dist(k0[1], k1[1])
            arc = math.sin(math.pi * core.clamp(u)) * min(10.0, 0.14 * d)
            p = _v_add(p, (0.0, -arc, 0.6 * arc))
            return _v_add(lap, p), _hand_mix(k0[2], k1[2], u), core.lerp(k0[3], k1[3], u)
    k = keys[-1]
    return _v_add(lap, k[1]), k[2], k[3]


