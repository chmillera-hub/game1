def _mean_tip(hf):
    xs = [p[0] for p in hf.tips]
    ys = [p[1] for p in hf.tips]
    return sum(xs) / len(xs), sum(ys) / len(ys)


def _hpt(hf, u, v=0.0):
    """A point in a hand's frame (body px along the fingers / across) -> world."""
    c, s = math.cos(hf.angle), math.sin(hf.angle)
    return hf.x + (c * u - s * v) * SC, hf.y + (s * u + c * v) * SC


def _palm_pt(hf, du=0.0):
    """Where a half rests on top of an open hand (world): a little along the fingers, then up."""
    x, y = _hpt(hf, PALM_U + du)
    return x, y - PALM_LIFT * SC


def _about(m, part, keep):
    """m with its rotation scaled by `keep` about the part's own centroid (keep 0: upright)."""
    cx, cy = SB.CENTROID[part]
    x0, y0 = m.transform_point(cx, cy)
    _x, _y, r, sc, _f = SB.decompose(m)
    out = SB.piece_matrix(x0, y0, r * keep, sc)
    out.translate(-cx, -cy)
    return out


def _at_centroid(x, y, part, rot=0.0):
    """A part's matrix with its centroid at world (x, y)."""
    m = SB.piece_matrix(x, y, rot, SC)
    cx, cy = SB.CENTROID[part]
    m.translate(-cx, -cy)
    return m


def _whole_matrix(t, rig):
    """The whole piece before the snap: on his near palm, rolled to the claw-tips as he lifts
    it, then between both claw-tips (level)."""
    hn, hf = rig.hand_near, rig.hand_far
    cx_, cy_ = _hpt(hn, CRADLE_U + 9.0 * core.inout_sine(core.clamp((t - T_LIFT) / 0.5)))   # it rolls toward his claw-tips
    cradle = (cx_, cy_ - CRADLE_LIFT * SC)
    if t < T_LIFT:
        return SB.piece_matrix(cradle[0], cradle[1], 0.0, SC)
    a, b = _mean_tip(hn), _mean_tip(hf)
    mid = ((a[0] + b[0]) * 0.5, (a[1] + b[1]) * 0.5 - TIP_LIFT * SC)
    w2 = core.inout_sine(core.clamp((t - (T_LIFT + 0.42)) / (T_HOLD2 - (T_LIFT + 0.42))))
    c = core.lerp_pt(cradle, mid, w2)
    return SB.piece_matrix(c[0], c[1], 0.0, SC)


def bread_layout(t, rig):
    """This frame's bread: [(who, part, world matrix)] -- who is the hold callback that draws it
    (its layer): "near" / "far" (his hands) or "gnome" (her hand: matrix None, she solves it);
    part 0 the whole piece, -1 her half (the left), +1 his half; plus ("gap", theta) while the
    tear opens. World matrices: piece units -> world px."""
    out = []
    if t < T_SNAP:
        whole = _whole_matrix(t, rig)
        th = 0.16 * strain_at(t)
        if th <= 0.0:
            out.append(("near", 0, whole))
        else:
            out.append(("near", "gap", (whole, th)))
            out.append(("near", -1, SB.half_matrix(whole, -1, th, 0.0)))
            out.append(("near", 1, SB.half_matrix(whole, 1, th, 0.0)))
        return out
    rel = _STATE.get("snap_rel")
    if rel is None:                                   # (setup, before the snap is measured)
        return out
    keep = 1.0 - core.inout_sine(core.clamp((t - T_PART) / 0.5))
    # his half: rides his far hand, then settles onto its palm in his lap
    mr = _about(rel[1].multiply(SB.hand_matrix(rig.hand_far)), 1, keep)
    u = core.inout_sine(core.clamp((t - T_PART) / 0.95))
    if u > 0.0:
        cx, cy = _palm_pt(rig.hand_far, -2.0)
        mr = SB.lerp_matrix(mr, _at_centroid(cx, cy, 1), u)
    out.append(("near" if t < T_PART else "far", 1, mr))
    # her half: rides his near hand; on the way to her it settles onto his palm
    if t >= T_SWITCH:
        out.append(("gnome", -1, None))
    elif t >= T_TAKE and "take_m" in _STATE:
        out.append(("near", -1, _STATE["take_m"]))
    else:
        ml = _about(rel[-1].multiply(SB.hand_matrix(rig.hand_near)), -1, keep)
        u = core.inout_sine(core.clamp((t - T_OFFER0) / (T_OFFER - T_OFFER0)))
        if u > 0.0:
            cx, cy = _palm_pt(rig.hand_near)
            ml = SB.lerp_matrix(ml, _at_centroid(cx, cy, -1), u)
        out.append(("near", -1, ml))
    return out


def _hold_cb(who, items, light):
    """A hand's hold callback drawing the bread items it holds this frame (through the camera:
    the hand gives the layer, the layout gives the place)."""
    mine = [it for it in items if it[0] == who]
    if not mine:
        return None
    cam_m = _STATE["cam_m"]

    def cb(cr, f):
        for _w, part, m in mine:
            if part == "gap":
                whole, th = m
                cr.save()
                cr.set_matrix(whole.multiply(cam_m))
                SB.draw_gap(cr, light, th, 0.0, strands=1.0)
                cr.restore()
            else:
                SB.draw_at(cr, m, cam_m, light, part)
    return cb


def with_bread(pose, items, light):
    """The dragon's pose with this frame's bread put in his hands."""
    near = pose.near.__class__(**{**pose.near.__dict__, "hold": _hold_cb("near", items, light)})
    far = pose.far.__class__(**{**pose.far.__dict__, "hold": _hold_cb("far", items, light)})
    return pose.with_(near=near, far=far)


def bread_points(items):
    """World centroids of this frame's bread (for its glow): {"whole"/"left"/"right": (x, y)}."""
    pts = {}
