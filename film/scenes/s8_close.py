class _soft_strum:
    """While S8 draws the bard: his strum's body rock attacks over ~4 frames instead of in one, and
    gentler (a quiet, silent strum) -- the lute and arms no longer jump on each stroke; the strum
    hand keeps its snap. (Patches bard._strum_state for the duration of one draw call only.)"""

    def __enter__(self):
        mod = ch.REGISTRY["bard"]
        self.mod, self.orig = mod, mod._strum_state

        def soft(pose, _orig=self.orig):
            st = _orig(pose)
            s_ = pose.strum_t
            if s_ is not None and s_ >= 0.0 and st.get("rock"):
                d = 1.0 if st["rock"] > 0 else -1.0
                st = dict(st, rock=0.55 * d * core.smooth(core.clamp(s_ / 0.17)) * math.exp(-s_ / 0.45))
            return st
        mod._strum_state = soft
        return self

    def __exit__(self, *exc):
        self.mod._strum_state = self.orig
        return False


def _g_s8_tale(q, sk, side, arm):
    """The dwarf's storytelling hand: hands on the knees (phase 0) <-> explaining in front of him
    (phase 1), lifted for the punchline (_GX["dw_lift"]), with a lively wiggle. The hand works in
    front of his own chest -- inside his silhouette, toward the ring -- never out sideways into
    the elf beside him. One continuous target with a constant hand, thumb and layer (blending two
    library gestures would flip the hand and swap the arm's layer mid-move)."""
    k = core.inout_sine(core.clamp(arm.phase))
    kn = _F.g_knees(q, sk, side, arm)
    AL = q.b.upper_arm + q.b.forearm
    w = _GX.get("dw_wiggle", 0.0) * k
    lift = _GX.get("dw_lift", 0.0) * (1.0 if side == q.near else 0.7)
    talk = _v_add(sk, (side * (0.02 + 0.04 * lift) * AL, (0.46 + 0.05 * w - 0.2 * lift) * AL, (0.5 + 0.1 * lift) * AL))
    tgt = _v_lerp(kn.target, talk, k)
    arc = math.sin(math.pi * k) * 0.04 * AL
    return _F.G(_v_add(tgt, (0.0, -arc, arc)), "relaxed", kn.hang, kn.layer, kn.pole, kn.thumb)


ch.REGISTRY["dwarf"].DWARF_GESTURES["s8_tale"] = _g_s8_tale


def dwarf_talk(t):
    """The dwarf's tale is a quiet murmur we never hear (the soundtrack is the dragon's thought):
    his beard wags as he tells it -- only BEFORE and AFTER the voice-over line, never under it
    (no mouth on screen may seem to speak the VO), and not in the breath after "stones"."""
    for ln in (L1, L2, L3):
        if ln.start - 0.3 <= t <= ln.end + 0.12:
            return 0.0
    k = _win(t, T_TALE0 + 0.08, L1.start - 0.35, 0.15, 0.2) + _win(t, T_PUNCH - 0.42, T_PUNCH + 0.2, 0.08, 0.12)
    if k <= 0.0:
        return 0.0
    syl = 0.5 + 0.5 * math.sin(t * math.tau * 3.1 + 1.3 * math.sin(t * 1.7))      # syllables
    return core.clamp(k * (0.12 + 0.42 * syl * (0.75 + 0.25 * core.noise1(t * 2.3, 44))))


def dwarf_pose(t):
    x, y = _STATE["b2"].place(U2["dwarf"])
    tale = _win(t, T_TALE0, T_TALE1, 0.4, 0.45)
    # the punchline: the hand comes up over 0.4 s (linear here: the gesture eases it once -- an
    # eased window on top of the eased gesture crammed the move into a single-frame jump)
    punch = min(core.clamp((t - (T_PUNCH - 0.4)) / 0.4), 1.0 - core.clamp((t - (T_LAUGH1 - 0.7)) / 0.5))
    laugh = laugh_win("dwarf", t, length=1.1, fi=0.08, fo=0.5)
    ring = _r(t, T_RING + 0.15, T_RING + 0.75)
    # the tale: his near hand explains in front of his chest (the bard sits too close on his far
    # side for that arm to wave); the punchline: the open hand comes up, palm to the sky ("...and
    # THAT was the last of the cheese!") -- and as the ring laughs he slaps his knee. One custom
    # gesture throughout (no hand flips, no layer swaps)
    slap = _r(t, T_LAUGH - 0.02, T_LAUGH + 0.14, "in_quad")
    wind = 0.12 * _bump(t, T_LAUGH - 0.24, 0.26)                 # the hand lifts a touch before it comes down
    _GX["dw_wiggle"] = math.sin(t * math.tau * 1.2)
    _GX["dw_lift"] = min(1.0, punch + wind)
    near = ch.Arm("s8_tale", phase=max(tale, punch) * (1.0 - slap))
    far = ch.Arm("s8_tale", phase=0.12 * tale)
    nod = 0.07 * tale * math.sin(t * 4.3) + 0.14 * laugh + 0.1 * punch
    nod += 0.07 * laugh * math.sin((t - T_LAUGH) * math.tau * 3.8 + 2.0) - 0.05 * B.wobble(t, T_LAUGH + 0.1, 5.0, 4.0)
    look = core.lerp_pt((-0.8, -0.1), (-0.85, 0.25), ring)          # in C: over to the two of them
    p = ch.DwarfPose(facing=-1, turn=0.55, sit=1.0, lamp_lit=True, mood="happy",
                     mood2=RING_CHUCKLE if laugh > 0 else None, mood_mix=laugh, laugh=0.0, talk=dwarf_talk(t),
                     lean=0.15 * tale - 0.14 * laugh + 0.08 * punch, head_nod=nod - 0.06 * ring, look=look,
                     near=near, far=far, seed=41)
    return x, y, p


