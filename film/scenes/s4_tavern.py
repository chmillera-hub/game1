def _pan(screen_x):
    return round(core.clamp(screen_x / core.W * 2.0 - 1.0, -1.0, 1.0), 2)


def _heel_strikes(t0, t1, dist_fn, stride_fn, dt=1.0 / 240.0):
    """Times at which a foot lands (walk phase crosses 0 or 0.5) while walking from t0 to t1."""
    out = []
    prev = None
    t = t0
    while t <= t1:
        ph = (dist_fn(t) / stride_fn(t)) % 1.0
        h = math.floor(ph * 2.0)
        if prev is not None and h != prev:
            out.append(t)
        prev = h
        t += dt
    return out


def _build_sfx():
    cues = []
    # the walk up (steps soften as he slows to a stop)
    stride_in = lambda t: ch.dragon_stride(SC_EXT, 1)                           # noqa: E731
    for tt in _heel_strikes(0.0, WALK_T2 + 0.1, lambda t: _walk_x(t) - DRAGON_X0, stride_in):
        walk = 1.0 - core.ramp(tt, WALK_T1 + 0.2, WALK_T2 + 0.15, "inout_sine")
        sx = _ext_cam_in(tt).to_screen(_walk_x(tt), S.EXT_GROUND)[0]
        cues.append((round(tt, 3), "footstep_wet", {"gain": round(0.45 + 0.4 * walk, 2), "pan": _pan(sx)}))
    # the last, softer step as he settles to a stop in front of the troll
    sx = _ext_cam_in(WALK_T2).to_screen(DRAGON_STOP, S.EXT_GROUND)[0]
    cues.append((round(WALK_T2 + 0.08, 3), "footstep_wet", {"gain": 0.45, "pan": _pan(sx)}))
    # the troll's wind-up (his leather jerkin creaks as the stamp goes up over his head)
    sx = _ext_cam_in(T_RAISE0).to_screen(TROLL_X, S.EXT_GROUND - 400.0)[0]
    cues.append((round(T_RAISE0 + 0.05, 3), "cloth_rustle", {"gain": 0.4, "pan": _pan(sx), "size": 1.4}))
    # the stamp: wood + felt on scales, the troll's whole weight behind it (at the hand)
    sx = _ext_cam_in(B_STAMP).to_screen(DRAGON_STOP + 110.0, S.EXT_GROUND - 200.0)[0]
    cues.append((round(B_STAMP, 3), "stamp_thunk", {"gain": 1.0, "pan": _pan(sx), "size": 1.4}))
    # inside: every volley of every synchronized laugh burst (one level, one rhythm: 280 HA per
    # minute), started a hair early so the recorded HAs peak with the mouths
    for a, b in LAUGH_BURSTS:
        for k in range(LAUGH_VOLLEYS[a]):
            ta = a + k * HA_VOLLEY - LAUGH_AUDIO_LEAD
            if B_INSIDE - 0.1 <= ta < SH_INT_C[1] - 0.4:
                cues.append((round(ta, 3), "laugh_crowd_burst", {"gain": 0.85, "pan": 0.25, "dur": round(HA_VOLLEY, 3),
                                                                 "bpm": S.LAUGH_BPM, "sync": True}))
            elif SH_INT_C[1] - 0.4 <= ta < DOOR_SHUT1:
                # heard from the street through the open door (it shuts on the tail)
                cues.append((round(ta, 3), "laugh_crowd_burst", {"gain": 0.6, "pan": 0.2, "dur": round(HA_VOLLEY, 3),
                                                                 "bpm": S.LAUGH_BPM, "sync": True, "dist": 0.6}))
    # his stamped hand: up to look at it, down again; the sigh; turning to go
    cues.append((round(T_HAND0 + 0.05, 3), "cloth_rustle", {"gain": 0.45, "pan": -0.1}))
    cues.append((round(T_SIGH + 0.1, 3), "sigh", {"gain": 0.6, "pan": -0.1}))
    cues.append((round(T_LOWER0 + 0.05, 3), "cloth_rustle", {"gain": 0.35, "pan": -0.1}))
    cues.append((round(B_EXIT + 0.15, 3), "cloth_rustle", {"gain": 0.4, "pan": -0.2}))
    # his first steps inside, toward the door (until the cut)
    for tt in _heel_strikes(T_GO, SH_INT_C[1] - 1e-3, lambda t: 52.0 * max(0.0, t - T_GO) ** 1.25,
                            lambda t: max(1.0, ch.dragon_stride(SC_INT, 1, _dragon_int_pose(t).turn))):
        cues.append((round(tt, 3), "footstep", {"gain": 0.4, "pan": -0.45}))
    # out on the street: steps on wet cobbles, the hands into the pockets, the door landing
    t0 = SH_EXT_OUT[0]

    for tt in _heel_strikes(t0, DUR - 1e-3, _exit_phase, lambda t: 1.0):
        x, y, sc, _d = _exit_path(tt)
        cam = _ext_cam_out(tt)
        cues.append((round(tt, 3), "footstep_wet", {"gain": 0.5, "pan": _pan(cam.to_screen(x, y)[0])}))
    x, y, sc, _d = _exit_path(T_POCKETS + 0.1)
    cues.append((round(T_POCKETS + 0.1, 3), "cloth_rustle", {"gain": 0.35, "pan": _pan(_ext_cam_out(T_POCKETS).to_screen(x, y)[0])}))
    for tt, kind, g in ((DOOR_SHUT0, "creak_wood", 0.5), (DOOR_SHUT1, "door_close", 1.0)):
        sx = _ext_cam_out(tt).to_screen(S.DOOR_CX, S.FAC_BASE - 150.0)[0]
        cues.append((round(tt, 3), kind, {"gain": g, "pan": _pan(sx), "size": 1.3}))
    cues.sort(key=lambda c: c[0])
    return [c for c in cues if 0.0 <= c[0] < DUR]


