T_POCKETS = SH_EXT_OUT[0] + 2.2           # the stamped hand goes into his coat pocket (as in S5)


def _exit_path(t):
    """(x, y, scale, distance walked) for the walk out: level along the foot of the facade."""
    u = max(0.0, t - SH_EXT_OUT[0])
    k = min(1.0, u / EXIT_ACC)
    ramp_int = EXIT_ACC * (k ** 3 - 0.5 * k ** 4) + max(0.0, u - EXIT_ACC)   # integral of smoothstep
    d = EXIT_V0 * u + (EXIT_V1 - EXIT_V0) * ramp_int
    return EXIT_X0 + d, EXIT_Y, SC_OUT, d


def _exit_turn(t):
    """His turn on the way out: 3/4 toward us as he comes out of the door, then profile along
    the street."""
    t0 = SH_EXT_OUT[0]
    return -0.5 * (1.0 - core.ramp(t, t0 + 0.3, t0 + 1.5, "inout_sine"))


_EXIT_PHASE = {}


def _exit_phase(t):
    """Walk phase on the way out, INTEGRATED (d distance / stride at that moment), so the feet stay
    planted while the stride changes with his turn and his scale (dist/stride would slip)."""
    t0 = SH_EXT_OUT[0]
    if not _EXIT_PHASE:
        dt = 1.0 / 240.0
        n = int(math.ceil((DUR - t0) / dt)) + 2
        ph, prev = [0.0], _exit_path(t0)
        for i in range(1, n):
            cur = _exit_path(t0 + i * dt)
            stride = ch.dragon_stride(cur[2], 1, _exit_turn(t0 + i * dt))
            ph.append(ph[-1] + (cur[3] - prev[3]) / max(1e-6, stride))
            prev = cur
        _EXIT_PHASE["dt"], _EXIT_PHASE["ph"] = dt, ph
    dt, ph = _EXIT_PHASE["dt"], _EXIT_PHASE["ph"]
    u = max(0.0, (t - t0) / dt)
    i = min(int(u), len(ph) - 2)
    return core.lerp(ph[i], ph[i + 1], u - i)


def _door_open_out(t):
    """1 = wide open .. 0 shut: it swings slowly, gathers speed and lands (door_close)."""
    u = core.ramp(t, DOOR_SHUT0, DOOR_SHUT1)
    return 1.0 - u ** 2.2


