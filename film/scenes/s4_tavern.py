    hope = core.ramp(t, t_glance, t_breath + 0.1) * (1.0 - core.ramp(t, B_SWELL, B_SWELL + 0.2))
    wince = core.ramp(t, B_SWELL, B_SWELL + 0.18) * (1.0 - core.ramp(t, SWELL_END - 0.3, SWELL_END + 0.3))
