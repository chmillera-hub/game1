    breath = core.window(t, t_breath, L1.start + 0.08, 0.16, 0.14)
    lean = (0.12 * core.ramp(t, L1.start - 0.05, L1.start + 0.4) * (1.0 - face) - 0.24 * sw - 0.06 * breath
            - 0.06 * core.window(t, B_TURN, B_LOOKB, 0.2, 0.4))
