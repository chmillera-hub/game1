DOF_RES = 0.5


def _dof_pass(cr, st, draw_fn, blur):
    """Depth of field for the close shot: draw_fn(c) paints the out-of-focus planes into a
    half-resolution buffer (cheap), which is blurred and laid down full-frame."""
    surf = st.get("dof_surf")
    if surf is None:
        surf = st["dof_surf"] = core.new_surface(int(core.W * DOF_RES), int(core.H * DOF_RES))
    c = core.new_context(surf)
    c.set_operator(cairo.OPERATOR_SOURCE)
    c.set_source_rgb(0, 0, 0)
    c.paint()
    c.set_operator(cairo.OPERATOR_OVER)
    c.scale(DOF_RES, DOF_RES)
    draw_fn(c)
    del c
    surf.flush()
    bl = fx.blur_surface(surf, blur * DOF_RES)
    cr.save()
    cr.identity_matrix()
    cr.scale(1.0 / DOF_RES, 1.0 / DOF_RES)
    cr.set_source_surface(bl, 0, 0)
    cr.get_source().set_filter(cairo.FILTER_BILINEAR)
    cr.paint()
    cr.restore()


