    e = e.blend(HOPE, hope)
    e = e.blend(WINCE, wince)
    e = e.blend(HURT, hurt * (1.0 - wince))
    e = e.blend(HOPE, 0.35 * listen)
    e = e.blend(WINCE, 0.32 * sting)
    e = e.blend(RESIGNED, core.ramp(t, T_SIGH + 0.3, T_SIGH + 0.6))
