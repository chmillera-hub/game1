BAND_CENTER = (880.0, 610.0)
WAVE_LIFE = 1.25
WAVE_DIR = math.atan2(575.0 - BAND_CENTER[1], DR_X + 40.0 - BAND_CENTER[0])     # toward his head
INSTRUMENTS = [(762.0, 575.0), (909.0, 650.0), (1046.0, 640.0)]                 # fiddle, tabor, shawm (world)


def _wave_list(t):
    """The swell's sound waves: one per jig beat for the swell's first ~1.3 s, all gone before
    the heads turn (the hush must be clean)."""
    out = []
    if t < B_SWELL - 0.05:
        return out
    for tb in S.jig_beats(B_SWELL - 0.02, min(t, B_SWELL + 1.05) + 1e-6):
        age = t - tb
        if 0.0 <= age < WAVE_LIFE:
            out.append((tb, age))
    return out


def _wave_hush(t):
    """Every wave still in flight is gone before the heads turn."""
    return 1.0 - core.ramp(t, B_TURN - 0.6, B_TURN - 0.15)


def _wave_alpha(tb, age):
    first = abs(tb - S.jig_beats(B_SWELL - 0.02, B_SWELL + 1.0)[0]) < 1e-6
    return (1.0 - age / WAVE_LIFE) ** 1.4 * (1.3 if first else 1.0) * _wave_hush(tb + age)


def _wave_radius(age):
    return 40.0 + 900.0 * core.out_quad(min(1.0, age / WAVE_LIFE))


def _swell_waves_light(lc, t):
    """Soft, broad bands of light riding the waves (in the LightLayer)."""
    for (tb, age) in _wave_list(t):
        r = _wave_radius(age)
        a = 0.2 * _wave_alpha(tb, age)
        col = S.HOT if int(round(tb / S.JIG_PERIOD)) % 2 else S.AMBER
        lc.save()
        lc.set_operator(cairo.OPERATOR_ADD)
        for (w, k) in ((150.0, 0.4), (60.0, 0.8)):
            lc.set_line_width(w)
            core.src(lc, col, a * k)
            lc.new_path()
            lc.arc(BAND_CENTER[0], BAND_CENTER[1], max(1.0, r - 20.0), WAVE_DIR - 1.0, WAVE_DIR + 1.0)
            lc.stroke()
        lc.restore()


def _swell_waves_back(cr, t):
    """The visible sound, part 1 (drawn in the world, BEHIND him, inside cam.view): for each beat,
    three concentric arcs (the house "sound" glyph, made huge) rolling out of the band across the
    room, wobbling like a vibrating string -- they break over the crowd and pass behind him, so his
    face stays clean (his mouth keeps moving under the noise)."""
    waves = _wave_list(t)
    if not waves:
        return
    cr.save()
    cr.set_operator(cairo.OPERATOR_ADD)
    cr.set_line_cap(1)
    for (tb, age) in waves:
        r0 = _wave_radius(age)
        a0 = 0.55 * _wave_alpha(tb, age)
        for k in range(3):
            r = r0 - 34.0 * k
            if r < 20:
                continue
            pts = []
            n = 28
            span = 0.85 - 0.12 * k
            for i in range(n + 1):
                th = WAVE_DIR - span + 2.0 * span * i / n
                rr = r * (1.0 + 0.02 * math.sin(th * 9.0 + tb * 7.0 + age * 14.0))
                pts.append((BAND_CENTER[0] + math.cos(th) * rr, BAND_CENTER[1] + math.sin(th) * rr))
            core.src(cr, S.HOT_PALE, a0 * (1.0 - 0.28 * k))
            cr.set_line_width(9.0 - 2.5 * k + 6.0 * age)
            core.smooth_open(cr, pts)
            cr.stroke()
    cr.restore()


def _swell_notes(cr, t, face=None, face_r=0.0):
    """The visible sound, part 2 (in front of him, inside cam.view): a storm of hot-pink notes
    flung from the fiddle, the tabor and the shawm at him -- they swarm round his head and are
    swallowed before they cross his face (face = his head centre, face_r its radius)."""
    for (x, y, size, ang, kind, col, alpha) in _note_list(t):
        if face is not None:
            d = math.hypot(x - face[0], (y - face[1]) * 1.15)
            alpha *= core.smoothstep(face_r * 0.9, face_r * 1.5, d)
        if alpha > 0.01:
            P.draw_music_note(cr, x, y, size, t, color=col, alpha=alpha, kind=kind, angle=ang, glow=True)


_NOTE_KINDS = ("semiminim", "fusa", "minim", "fusa")


def _note_list(t):
    """Notes in flight at t: (x, y, size, angle, kind, colour, alpha)."""
    out = []
    if t < B_SWELL - 0.05 or t > SWELL_END + 1.2:
        return out
    beats = S.jig_beats(B_SWELL - 0.02, B_SWELL + 1.05)
    k = 0
    for bi, tb in enumerate(beats):
        for half in (0.0, 0.5):
            t_birth = tb + half * S.JIG_PERIOD
            for j, src in enumerate(INSTRUMENTS):
                k += 1
                if half > 0 and j == 1:
                    continue
                life = 0.8 + 0.25 * core.hash01(k, 41)
                u = (t - t_birth) / life
                if u < 0.0 or u > 1.3:
                    continue
                ang_k = math.tau * core.hash01(k, 43)                    # a ring round his head
                tx = DR_X + 48.0 + math.cos(ang_k) * (95.0 + 50.0 * core.hash01(k, 44))
                ty = 572.0 + math.sin(ang_k) * (80.0 + 40.0 * core.hash01(k, 44))
                cx, cy = (src[0] + tx) / 2 + (core.hash01(k, 45) - 0.5) * 120.0, min(src[1], ty) - 60.0 - 90.0 * core.hash01(k, 46)
                e = core.out_quad(min(1.0, u))
                if u <= 1.0:
                    x = (1 - e) ** 2 * src[0] + 2 * (1 - e) * e * cx + e * e * tx
                    y = (1 - e) ** 2 * src[1] + 2 * (1 - e) * e * cy + e * e * ty
                else:                                   # past him: carries on along the tangent
                    dx, dy = 2 * (tx - cx), 2 * (ty - cy)
                    x = tx + dx * (u - 1.0) * 0.35
                    y = ty + dy * (u - 1.0) * 0.35
                size = 1.2 + 1.9 * min(1.0, u)
                ang = (core.hash01(k, 47) - 0.5) * 0.8 + math.sin(t * 6.0 + k) * 0.25 * min(1.0, u)
                # they crowd round his face and are gone as they reach it (they swallow his words,
                # they never cover his face)
                alpha = core.ramp(u, 0.0, 0.08) * (1.0 - core.ramp(u, 0.72, 0.98)) * (1.0 - core.ramp(t, B_TURN - 0.45, B_TURN - 0.1))
                col = (S.HOT, "#ff7ab8", S.AMBER)[k % 3]
                out.append((x, y, size, ang, _NOTE_KINDS[k % 4], col, alpha))
    return out


VOICE_COLOR = "#e6e4f6"


def _voice_ripples(cr, t, drig):
    """His small, honest voice: thin pale ripples from his mouth while he speaks -- they travel
    before the swell, and are crushed (swallowed) the instant it hits. Cool silver-lilac, never
    gold: the first warm light that comes from HIM is the laugh's embers in S6 (SPEC 0.3, 4)."""
    if not (L1.start - 0.05 <= t <= L1.end + 0.6):
        return
    mx, my = drig.mouth
    s = drig.scale
    born = []
    k = L1.start
    while k <= min(t, L1.end):
        if tl.talk(SCENE, k, "MAN") > 0.28:
            born.append(k)
        k += 0.2
    for tb in born:
        age = t - tb
        life = 0.9 if tb < B_SWELL else 0.22
        if age < 0 or age > life:
            continue
        u = age / life
        r = (14.0 + (95.0 if tb < B_SWELL else 16.0) * core.out_cubic(u)) * s
        if t > B_SWELL and tb < B_SWELL:
            # the wave reaches him: the ripples in flight are crushed
            crush = core.ramp(t, B_SWELL + 0.05, B_SWELL + 0.25)
            r *= 1.0 - 0.6 * crush
            u = max(u, crush)
        a = 0.85 * (1.0 - u) ** 1.2
        if a <= 0.01:
            continue
        cr.save()
        cr.set_line_width(max(1.0, 3.6 * s))
        core.src(cr, VOICE_COLOR, a)
        cr.arc(mx + 8 * s, my, r, -0.55, 0.55)
        cr.stroke()
        cr.restore()


