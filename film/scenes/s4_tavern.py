def _crowd_pose_for(t, spec, facing, turn, who, lp, up, a, sit=False):
    """A laughing patron, or (for a turner after s4_turn) one who stopped mid-laugh to stare."""
    ha_phase = (t - a) * 2.33 if a is not None else 0.0
    kw = dict(facing=facing, turn=turn)
    if sit:
        kw.update(sit=1.0, seat_h=125.0)
    if who in TURNERS and B_TURN <= t < T_REJOIN + 0.35:
        # frozen mid-laugh: the HA and the tankard stop where they were; the head turns to stare
        lp0, up0, a0 = laugh_state(B_TURN)
        ph0 = (((B_TURN - a0) * 2.33) % 1.0) - 1.0 if a0 is not None else -1.0   # the arm stops where it was
        lp0 = max(lp0, 0.85)                       # frozen with the mouth still open on the HA
        u = core.ramp(t, B_TURN, B_TURN + 0.28, "out_back")
        up0 *= 1.0 - core.ramp(t, B_TURN + 0.45, B_TURN + 1.35, "inout_sine")   # the toast forgotten: it sinks
        talk = (0.4 + 0.6 * lp0) * (1.0 - core.ramp(t, B_TURN + 0.1, B_TURN + 0.6))
        stare = (-0.85, 0.15)
        head_turn = -0.55 * u
        mood = "skeptical" if who != 1 else "bored"
        yaw = None
        if who == "starer":
            # he faces the dragon already: only a small turn; his eyes do the staring
            head_turn = 0.25 * u
            stare = (-0.7, 0.25)
        nod = 0.25 * (1.0 - u) + 0.05
        if who == "someone":
            # (left of the dragon, facing the room) he looks round at the dragon: eyes, then head
            head_turn = 0.0
            stare = core.lerp_tuple((0.3, 0.0), (0.9, -0.35), u)
            nod = 0.1 + 0.15 * (1.0 - u)
            if t >= B_LOOKB - 0.15:
                # ...then the look to the troll: eyes flick first, then he swings round to face
                # the doorway (the body follows the head), and a jerk of the chin up at him
                ev = core.ramp(t, B_LOOKB - 0.15, B_LOOKB + 0.05, "out_cubic")
                v = core.ramp(t, B_LOOKB, B_LOOKB + 0.45, "inout_sine")
                yaw = core.lerp(0.75, -0.95, v)
                stare = core.lerp_tuple(stare, (-1.0, -0.6), ev)
                stare = core.lerp_tuple(stare, (-0.5, -0.7), v)
                nod = 0.1 - 0.25 * v + 0.3 * core.window(t, B_LOOKB + 0.5, B_LOOKB + 1.1, 0.1, 0.4)
                mood = "skeptical"
        # ...and when the troll has dealt with it, they rejoin the machine on the next burst
        back = core.ramp(t, T_REJOIN, T_REJOIN + 0.35, "inout_sine")
        if back > 0:
            lpn = 0.55 + 0.45 * lp
            talk = core.lerp(talk, 0.4 + 0.6 * lpn, back)
            head_turn = core.lerp(head_turn, 0.0, back)
            nod = core.lerp(nod, 0.25 + 0.2 * lpn, back)
            stare = core.lerp_tuple(stare, (0.0, 0.0), back)
            up0 = core.lerp(up0, up, back)
            ph0 = core.lerp(ph0, (ha_phase % 1.0) - 1.0, back)      # hand over to the laugh path's arm
            if yaw is not None:
                yaw = core.lerp(yaw, 0.75, back)
        if yaw is not None:
            kw["yaw"] = yaw
        p = ch.CrowdPose(action="idle", tankard=True, mood=mood if back < 0.5 else "happy", talk=talk,
                         laugh=core.lerp(0.7 * (1.0 - u), 0.7, back),
                         look=stare, head_turn=head_turn, head_nod=nod,
                         near=ch.Arm("s4_toast", amt=up0, prev="tankard", phase=ph0), seed=spec.seed, **kw)
        return p
    # between bursts: everyone holds the SAME frozen grin and takes the same breath (a held
    # beat, eyes still squeezed, tankards at the chest), then they all burst again on one frame
    # everyone on the laugh clock shares ONE pose seed: the same breath, the same shake, even
    # the same blinks -- a machine, not a crowd
    kw["seed"] = SYNC_SEED
    # one phase drives both gestures: the cheer's pump is periodic, the tankard's toast height is
    # clamped -- kept in [-1, 0) the blend always starts from (and comes back down to) the chest
    p = ch.crowd_pose("laugh", t, spec, laugh_pulse=0.55 + 0.45 * lp, amount=1.0,
                      near=ch.Arm("s4_toast", amt=up, prev="tankard", phase=(ha_phase % 1.0) - 1.0), **kw)
    g = grin_k(t)
    if g > 0.0:
        # between bursts: the SAME frozen grin on every face, held (a beat too long), tankards at
        # the chest; then they all burst again on one frame
        lpb = p.laugh_pulse
        talk_b, nod_b, laugh_b = 0.4 + 0.6 * lpb, 0.25 + 0.2 * lpb, max(p.laugh, 0.7)      # as crowd.py draws a laugh
        p = p.with_(action="idle", tankard=True, mood="happy", smile=1.0,
                    talk=core.lerp(talk_b, 0.04, g), laugh=core.lerp(laugh_b, 0.0, g),
                    head_nod=core.lerp(nod_b, 0.06, g), look=(0.0, 0.0))
    return p


SYNC_SEED = 7


def grin_k(t):
    """0 while a laugh burst is running, 1 in the frozen grin between bursts (fast in/out)."""
    k = 1.0
    for a, b in LAUGH_BURSTS:
        k = min(k, 1.0 - core.window(t, a - 0.06, b + 0.06, 0.06, 0.12))
    return k


def _fiddle(cr, chin, hand, s, light):
    """The fiddler's fiddle: tucked under the chin, its neck running to the far (fretting) hand.
    The bow is drawn after the near arm (_fiddle_bow)."""
    dx, dy = hand[0] - chin[0], hand[1] - chin[1]
    ang = math.atan2(dy, dx)
    L = math.hypot(dx, dy)
    cr.save()
    cr.translate(chin[0], chin[1] + 6 * s)
    cr.rotate(ang)
    lw = max(1.0, 1.6 * s)
    body = [(-4 * s, -16 * s), (14 * s, -19 * s), (26 * s, -12 * s), (30 * s, 0), (26 * s, 12 * s), (14 * s, 19 * s), (-4 * s, 16 * s), (-10 * s, 0)]
    core.smooth_closed(cr, B.offset_closed(body, lw), 0.8)
    core.src(cr, "#2a1008")
    cr.fill()
    core.smooth_closed(cr, body, 0.8)
    core.src(cr, B.palette(light, B.Mat.of("#a4501e", sheen=0.6)).lit)
    cr.fill()
    core.src(cr, "#ffd0a0", 0.35)
    core.ellipse(cr, 8 * s, -8 * s, 7 * s, 3 * s, -0.3)
    cr.fill()
    cr.rectangle(28 * s, -3 * s, max(10.0, L - 30 * s), 6 * s)            # the neck
    core.src(cr, "#2a1008")
    cr.fill()
    core.src(cr, "#5a2a14")
    core.circle(cr, L, 0, 4.5 * s)                                         # the scroll
    cr.fill()
    cr.set_line_width(max(0.6, 0.6 * s))
    core.src(cr, "#f0e0c0", 0.7)
    for k in (-2, 2):
        cr.move_to(4 * s, k * s)
        cr.line_to(L, k * s * 0.4)
    cr.stroke()
    cr.restore()



def _draw_band(cr, t, st, L):
    """The fiddler (satyr), the drummer (dwarf) and a piper (goblin) on the dais. The jig drives
    the bowing and the drumming; at the swell they surge (lean in, bigger strokes)."""
    sw = swell_k(t)
    sc = BAND_SC
    # the surge: on every beat of the swell they hop and lean into it together
    hop = 7.0 * sw * S.jig_pulse(t, lilt=0.0)
    # ---- fiddler: facing the room (right), the fiddle on his left shoulder (far side)
    spec = st["specs"]["fiddler"]
    bow = math.sin(t * math.tau * (S.JIG_BPM / 60.0) * (1.5 + 1.0 * sw))
    fp = ch.CrowdPose(action="idle", facing=1, turn=-0.55, mood="happy", seed=spec.seed, lean=0.12 * sw - 0.05,
                      head_tilt=0.22 + 0.06 * sw, head_nod=-0.15, look=(0.3, 0.3), smile=0.7, talk=0.1,
                      near=ch.Arm("point", target=(-20.0 + 28.0 * bow * (1 + 0.6 * sw), -300.0 + 8.0 * bow, 62.0), hand="grip"),
                      far=ch.Arm("point", target=(58.0, -318.0, 72.0), hand="grip"))
    fx_ = 742.0
    fy_ = BAND_Y - hop
    if _on_screen(fx_, fy_, 430.0 * sc):
        r = ch.draw_crowd(cr, fx_, fy_, sc, spec, fp, L, t, parts=("back", "body", "mid", "head"))
        chin = (r.mouth[0] + 4 * sc, r.mouth[1] + 14 * sc)
        _fiddle(cr, chin, (r.hand_far.x, r.hand_far.y), sc * 1.35, L)
        r2 = ch.draw_crowd(cr, fx_, fy_, sc, spec, fp, L, t, parts=("front",))
        _fiddle_bow(cr, (r2.hand_near.x, r2.hand_near.y), chin, sc * 1.35, (r.hand_far.x, r.hand_far.y))
    # ---- drummer: a tabor on a stand, two sticks, alternating on the beat
    spec = st["specs"]["drummer"]
    hit_n = (t / (S.JIG_PERIOD / (2.0 + 2.0 * sw)))
    ph = hit_n % 2.0
    upL = abs(math.sin(math.pi * min(1.0, ph)))
    upR = abs(math.sin(math.pi * max(0.0, ph - 1.0)))
    big = 1.0 + 0.8 * sw
    dp = ch.CrowdPose(action="idle", facing=0, turn=0.35, mood="happy", seed=spec.seed, lean=0.1 + 0.15 * sw,
                      head_nod=-0.2 + 0.1 * upL, smile=0.6, talk=0.15 + 0.4 * sw,
                      near=ch.Arm("point", target=(-62.0, -150.0 - 64.0 * upL * big, 52.0), hand="fist"),
                      far=ch.Arm("point", target=(64.0, -150.0 - 64.0 * upR * big, 52.0), hand="fist"))
    dx_ = 905.0
    dy_ = BAND_Y - hop
    if _on_screen(dx_, dy_, 300.0 * sc):
        r = ch.draw_crowd(cr, dx_, dy_, sc, spec, dp, L, t, parts=("back", "body", "mid", "head"))
        _tabor(cr, dx_ + 4 * sc, BAND_Y - 120 * sc, sc, L, sw)
        r2 = ch.draw_crowd(cr, dx_, dy_, sc, spec, dp, L, t, parts=("front",))
        for hf in (r2.hand_near, r2.hand_far):
            _stick(cr, (hf.x, hf.y), (dx_ + 4 * sc, BAND_Y - 128 * sc), sc)
    # ---- piper: a goblin on a shawm, swaying
    spec = st["specs"]["piper"]
    # the shawm's bell lifts on the swell (he blasts it at the room)
    lift = 0.25 + 0.55 * sw + 0.06 * math.sin(t * 7.0)
    pp = ch.CrowdPose(action="idle", facing=1, turn=-0.45, mood="happy", seed=spec.seed, lean=0.05 - 0.15 * sw,
                      head_nod=0.1 + 0.35 * lift, look=(-0.2, -0.4), talk=0.0,
                      near=ch.Arm("point", target=(-12.0, -138.0 - 34.0 * lift, 108.0), hand="grip"),
                      far=ch.Arm("point", target=(0.0, -162.0 - 28.0 * lift, 80.0), hand="grip"))
    px_ = 1010.0
    if _on_screen(px_, BAND_Y, 300.0 * sc):
        r = ch.draw_crowd(cr, px_, BAND_Y + 2 - hop, sc, spec, pp, L, t)
        _shawm(cr, r.mouth, (r.hand_near.x, r.hand_near.y), sc, sw)


def _shawm(cr, mouth, hand, s, sw):
    """The goblin's shawm: a long conical wooden pipe from his lips through his lower hand,
    flaring to a bell (finger holes, a brass ring), with a hot glint on the swell."""
    a = math.atan2(hand[1] - mouth[1], hand[0] - mouth[0])
    L = 118.0 * s
    ca, sa = math.cos(a), math.sin(a)
    nx, ny = -sa, ca
    tip = (mouth[0] + ca * 4 * s, mouth[1] + sa * 4 * s)
    end = (mouth[0] + ca * L, mouth[1] + sa * L)
    w0, w1 = 3.2 * s, 7.5 * s
    pts = [(tip[0] + nx * w0, tip[1] + ny * w0), (end[0] + nx * w1, end[1] + ny * w1),
           (end[0] + nx * w1 * 2.4 + ca * 10 * s, end[1] + ny * w1 * 2.4 + sa * 10 * s),
           (end[0] - nx * w1 * 2.4 + ca * 10 * s, end[1] - ny * w1 * 2.4 + sa * 10 * s),
           (end[0] - nx * w1, end[1] - ny * w1), (tip[0] - nx * w0, tip[1] - ny * w0)]
    cr.save()
    lw = max(1.0, 1.6 * s)
    cr.new_path()
    core.polygon(cr, B.offset_closed(pts, lw))
    core.src(cr, "#2a140a")
    cr.fill()
    core.polygon(cr, pts)
    core.src(cr, "#c8904a")
    cr.fill()
    core.src(cr, "#7a4a24", 0.8)
    core.polygon(cr, [(tip[0] - nx * w0 * 0.2, tip[1] - ny * w0 * 0.2), (end[0] - nx * w1 * 0.3, end[1] - ny * w1 * 0.3),
                      (end[0] - nx * w1, end[1] - ny * w1), (tip[0] - nx * w0, tip[1] - ny * w0)])
    cr.fill()
    core.src(cr, "#2a140a", 0.9)
    for k in range(4):                                      # finger holes
        u = 0.32 + 0.12 * k
        core.circle(cr, mouth[0] + ca * L * u + nx * 1.0 * s, mouth[1] + sa * L * u + ny * 1.0 * s, 1.3 * s)
    cr.fill()
    core.src(cr, "#e8c46a")                                 # brass ring at the bell
    rx, ry = mouth[0] + ca * (L - 2 * s), mouth[1] + sa * (L - 2 * s)
    core.polygon(cr, [(rx + nx * w1 * 1.1, ry + ny * w1 * 1.1), (rx + nx * w1 * 1.1 + ca * 4 * s, ry + ny * w1 * 1.1 + sa * 4 * s),
                      (rx - nx * w1 * 1.1 + ca * 4 * s, ry - ny * w1 * 1.1 + sa * 4 * s), (rx - nx * w1 * 1.1, ry - ny * w1 * 1.1)])
    cr.fill()
    if sw > 0.05:
        fx.glow(cr, end[0] + ca * 12 * s, end[1] + sa * 12 * s, 40 * s, "#ffd0a0", 0.5 * sw)
    cr.restore()


def _fiddle_bow(cr, hand, chin, s, scroll):
    ang = math.atan2(scroll[1] - chin[1], scroll[0] - chin[0])
    tx, ty = chin[0] + math.cos(ang) * 6 * s, chin[1] + 6 * s + math.sin(ang) * 6 * s
    bx, by = hand
    ba = math.atan2(ty - by, tx - bx)
    ext = 64 * s
    cr.save()
    cr.set_line_cap(1)
    cr.set_line_width(max(1.0, 1.9 * s))
    core.src(cr, "#2a1208")
    cr.move_to(bx - math.cos(ba) * 8 * s, by - math.sin(ba) * 8 * s)
    cr.line_to(tx + math.cos(ba) * ext, ty + math.sin(ba) * ext)
    cr.stroke()
    cr.set_line_width(max(0.5, 0.8 * s))
    core.src(cr, "#f4ead8", 0.85)
    nx, ny = math.sin(ba) * 3.2 * s, -math.cos(ba) * 3.2 * s
    cr.move_to(bx - math.cos(ba) * 6 * s + nx, by - math.sin(ba) * 6 * s + ny)
    cr.line_to(tx + math.cos(ba) * ext + nx, ty + math.sin(ba) * ext + ny)
    cr.stroke()
    cr.restore()


def _tabor(cr, x, y, s, light, sw):
    """A medieval tabor (a deep two-headed drum) on a stand, the near head toward us."""
    w, h = 64 * s, 46 * s
    cr.save()
    cr.set_line_width(max(1.0, 2.0 * s))
    core.src(cr, "#2a1410")
    cr.move_to(x - w * 0.3, y + h * 0.5)
    cr.line_to(x - w * 0.42, y + 120 * s)
    cr.move_to(x + w * 0.3, y + h * 0.5)
    cr.line_to(x + w * 0.42, y + 120 * s)
    cr.stroke()
    cr.rectangle(x - w / 2, y - h / 2, w, h)
    core.src(cr, B.palette(light, B.Mat.of("#9a3a2a")).lit)
    cr.fill()
    cr.set_line_width(max(0.6, 1.0 * s))
    core.src(cr, "#e8d0a0", 0.7)
    for k in range(6):
        u = k / 5.0
        cr.move_to(x - w / 2 + w * u, y - h / 2)
        cr.line_to(x - w / 2 + w * ((k + 0.5) / 5.0 if k < 5 else 1.0), y + h / 2)
