# the synchronized laugh: bursts (everyone on the same HA), each opening with the tankards
# thrown up together; between bursts a frozen grin and a synchronized breath. A burst is made of
# VOLLEYS -- one 'laugh_crowd_burst' cue each, six HAs on the laugh clock (the recorded laugh has
# the same rate) -- so the mouths stop when the sound does: the last HA's open mouth is held a
# beat, the tankards come down, the grin freezes. In the hush after the second burst he finally
# speaks (s4_l1); the swell's burst is two volleys long, so the room is still laughing when the
# starers' heads stop mid-HA at s4_turn.
HA_VOLLEY = 6 * 60.0 / S.LAUGH_BPM                      # one volley: six HAs (~1.29 s)
LAUGH_TAIL = 0.16                                       # the last HA held before the grin
LAUGH_AUDIO_LEAD = 0.04                                 # the recorded HAs peak ~1.5 frames after onset
_BURST_VOLLEYS = [(B_INSIDE, 1), (B_INSIDE + 2.25, 1), (B_SWELL, 2), (B_TURN + 0.95, 1),
                  (L2.start + 0.4, 1), (L2.end + 0.95, 1), (B_EXIT + 0.75, 1)]
LAUGH_VOLLEYS = dict(_BURST_VOLLEYS)
LAUGH_BURSTS = [(a, B_TURN + 0.55 if a == B_SWELL else a + n * HA_VOLLEY + LAUGH_TAIL) for a, n in _BURST_VOLLEYS]


def laugh_state(t):
    """(lp, raise_k, burst_start): the HA pulse, how high the tankards are (0 chest .. 1
    overhead), and the start of the current burst (None between bursts)."""
    for a, b in LAUGH_BURSTS:
        if a - 0.2 <= t <= b + 0.25:
            up = core.ramp(t, a - 0.14, a + 0.16, "out_back") * (1.0 - core.ramp(t, b - 0.1, b + 0.25, "inout_sine"))
            lp = S.laugh_sync(t, a) if a <= t <= min(b, a + LAUGH_VOLLEYS[a] * HA_VOLLEY) else 0.0
            return lp, up, a
    return 0.0, 0.0, None


