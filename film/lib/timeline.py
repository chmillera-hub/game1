"""timeline.py -- the single source of timing truth for scenes.

Loads film/timeline.json (written by film/audio/tts.py) or the file named by the environment
variable FILM_TIMELINE (e.g. FILM_TIMELINE=film/build/stub_timeline.json for testing).
All times on Scene/Line/Beat objects are LOCAL scene seconds unless prefixed global_.

    from film.lib import timeline as tl
    sc = tl.scene(3)                 # .start (global) .duration .name .end
    ln = tl.line("s3_l4")            # .start .end (local) .text .speaker .env .global_start ...
    bt = tl.beat("s3_hold")          # .t .end (local; end may be None)
    tl.talk(3, t, "MAN")             # 0..1 mouth openness from the real speech envelope
    tl.speaking(3, t, "MAN")         # bool

Make a stub for testing:  python3 -m film.lib.timeline --stub film/build/stub_timeline.json
"""

