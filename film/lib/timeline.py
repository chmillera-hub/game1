# 5-tap smoothing kernel over +-2/48 s: gives the mouth a ~40 ms attack/release and removes
# frame-to-frame chatter while staying in sync with the syllables.
_KERNEL = ((-2, 1.0), (-1, 2.0), (0, 3.0), (1, 2.0), (2, 1.0))
_KSUM = 9.0


def talk(scene_n, t, speaker, gain=1.0):
    """Mouth openness 0..1 for `speaker` at local time t: the line's speech envelope, smoothed,
    with a tiny attack/release so mouths never snap. 0 outside that speaker's lines."""
    lines = lines_in(scene_n, speaker)
    if not lines:
        return 0.0
    dt = 1.0 / (2.0 * fps())
    act = [ln for ln in lines if ln.start - 0.1 <= t <= ln.end + 0.1]
    if not act:
        return 0.0
    v = 0.0
    for k, w in _KERNEL:
        tt = t + k * dt
        for ln in act:
            v += w * ln.env_at(tt)
    v = v / _KSUM * gain
    return 0.0 if v < 0.0 else 1.0 if v > 1.0 else v


def speaking(scene_n, t, speaker):
    """True while one of the speaker's lines is active at local time t."""
    return any(ln.start <= t <= ln.end for ln in lines_in(scene_n, speaker))


def word_times(line_id):
    """Estimated (word, t_start_local, t_end_local) for each word of a line, aligned to the
    speech envelope (cumulative energy), for word-by-word reveals such as S3's rune text."""
    ln = line(line_id)
    words = ln.text.split()
    if not words:
        return []
    env = ln.env or [1.0] * max(1, int(ln.duration * fps()))
    cum = [0.0]
    for v in env:
        cum.append(cum[-1] + max(0.0, v))
    total_e = cum[-1] or 1.0
    weights = [len(w.strip(".,!?…;:-—\"'")) + 1 for w in words]
    wsum = float(sum(weights))
    out, acc = [], 0.0

    def time_at(frac):
        target = frac * total_e
        for i in range(1, len(cum)):
            if cum[i] >= target:
                f = (target - cum[i - 1]) / max(1e-9, cum[i] - cum[i - 1])
                return ln.start + (i - 1 + f) / fps()
        return ln.end

    for w, wt in zip(words, weights):
        a = time_at(acc / wsum)
        acc += wt
        b = time_at(acc / wsum)
        out.append((w, a, min(b, ln.end)))
    return out


