def _missing(kind, key, pool):
    near = [k for k in pool if str(key).split("_")[0] in str(k)][:12]
    return KeyError(f"{kind} {key!r} not in {path()}  (same scene: {near})")


def scene(n):
    d = _load()["scenes"]
    if int(n) not in d:
        raise _missing("scene", n, d)
    return d[int(n)]


def line(line_id):
    d = _load()["lines"]
    if line_id not in d:
        raise _missing("line", line_id, d)
    return d[line_id]


def has_line(line_id):
    return line_id in _load()["lines"]


def beat(beat_id):
    d = _load()["beats"]
    if beat_id not in d:
        raise _missing("beat", beat_id, d)
    return d[beat_id]


def has_beat(beat_id):
    return beat_id in _load()["beats"]


def lines_in(scene_n, speaker=None):
    out = _load()["by_scene"].get(int(scene_n), [])
    return [ln for ln in out if speaker is None or ln.speaker == speaker]


def beats_in(scene_n):
    return sorted((b for b in _load()["beats"].values() if b.scene == int(scene_n)), key=lambda b: b.t)


def to_global(scene_n, t_local):
    return scene(scene_n).start + t_local


def to_local(scene_n, t_global):
    return t_global - scene(scene_n).start


def active_line(scene_n, t, speaker=None):
    """The line (of `speaker`, if given) being spoken at local time t, or None."""
    for ln in lines_in(scene_n, speaker):
        if ln.start <= t <= ln.end:
            return ln
    return None


