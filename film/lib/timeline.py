def path():
    """The timeline file in use (FILM_TIMELINE overrides film/timeline.json)."""
    p = os.environ.get("FILM_TIMELINE")
    if p:
        p = Path(p)
        return p if p.is_absolute() else ROOT / p
    return DEFAULT_PATH


def _load():
    global _data, _path
    p = path()
    if _data is not None and _path == p:
        return _data
    if not p.exists():
        raise FileNotFoundError(
            f"timeline not found: {p}\n  It is generated by film/audio/tts.py. For testing, make a stub with\n"
            f"  python3 -m film.lib.timeline --stub film/build/stub_timeline.json\n"
            f"  and run with FILM_TIMELINE=film/build/stub_timeline.json")
    with open(p) as f:
        raw = json.load(f)
    d = {
        "raw": raw,
        "fps": int(raw.get("fps", 24)),
        "scenes": {int(s["id"]): Scene(s) for s in raw.get("scenes", [])},
        "lines": {},
        "beats": {},
    }
    for ld in raw.get("lines", []):
        ln = Line(ld)
        d["lines"][ln.id] = ln
    for bd in raw.get("beats", []):
        b = Beat(bd)
        d["beats"][b.id] = b
    by_scene = {}
    for ln in d["lines"].values():
        by_scene.setdefault(ln.scene, []).append(ln)
    for v in by_scene.values():
        v.sort(key=lambda x: x.start)
    d["by_scene"] = by_scene
    _data, _path = d, p
    return d


def reload():
    global _data
    _data = None
    return _load()


def raw():
    """The parsed JSON dict."""
    return _load()["raw"]


def fps():
    return _data["fps"] if _data is not None else _load()["fps"]


def total():
    return float(_load()["raw"].get("total", 0.0))


def cast():
    return _load()["raw"].get("cast", {})


def scenes():
    return [v for _, v in sorted(_load()["scenes"].items())]


