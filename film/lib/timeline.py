DEFAULT_PATH = ROOT / "film" / "timeline.json"

_data = None
_path = None


class Scene:
    __slots__ = ("id", "name", "start", "duration")

    def __init__(self, d):
        self.id = int(d["id"])
        self.name = d.get("name", f"s{self.id}")
        self.start = float(d["start"])
        self.duration = float(d["duration"])

    @property
    def end(self):
        return self.start + self.duration

    @property
    def frames(self):
        return int(round(self.duration * fps()))

    def __repr__(self):
        return f"Scene({self.id}, {self.name!r}, start={self.start}, duration={self.duration})"


class Line:
    __slots__ = ("id", "scene", "speaker", "text", "start", "end", "global_start", "global_end",
                 "wav", "caption", "vo", "fx", "env", "raw")

    def __init__(self, d):
        self.raw = d
        self.id = d["id"]
        self.scene = int(d["scene"])
        self.speaker = d["speaker"]
        self.text = d.get("text", "")
        self.start = float(d["start"])
        self.end = float(d["end"])
        self.global_start = float(d.get("global_start", self.start))
        self.global_end = float(d.get("global_end", self.end))
        self.wav = d.get("wav")
        self.caption = bool(d.get("caption", True))
        self.vo = bool(d.get("vo", False))
        self.fx = d.get("fx")
        self.env = [float(v) for v in (d.get("env") or [])]

    @property
    def duration(self):
        return self.end - self.start

    def env_at(self, t_local):
        """Raw (linearly interpolated) speech envelope at local scene time; 0 outside."""
        if t_local < self.start or t_local > self.end or not self.env:
            return 0.0
        x = (t_local - self.start) * fps()
        i = int(math.floor(x))
        if i >= len(self.env) - 1:
            return self.env[-1] if i == len(self.env) - 1 else 0.0
        f = x - i
        return self.env[i] * (1.0 - f) + self.env[i + 1] * f

    def __repr__(self):
        return f"Line({self.id!r}, {self.speaker}, {self.start:.2f}-{self.end:.2f}, {self.text!r})"


class Beat:
    __slots__ = ("id", "scene", "t", "end")

    def __init__(self, d):
        self.id = d["id"]
        self.scene = int(d["scene"])
        self.t = float(d["t"])
        self.end = None if d.get("end") is None else float(d["end"])

    @property
    def dur(self):
        return 0.0 if self.end is None else self.end - self.t

    def __repr__(self):
        return f"Beat({self.id!r}, t={self.t}, end={self.end})"


