def _synthetic_env(text, dur, rate=24, seed=0):
    """Plausible syllabic envelope: ~4.5 bumps/s, dips at word gaps and punctuation."""
    n = max(2, int(round(dur * rate)))
    words = text.split()
    env = []
    for i in range(n):
        t = i / rate
        u = t / dur
        syl = abs(math.sin(math.pi * t * 4.6 + seed)) ** 0.8
        wi = min(len(words) - 1, int(u * len(words)))
        pause = 0.35 if words and words[wi][-1:] in ".,?!…—" and (u * len(words)) % 1 > 0.8 else 1.0
        edge = min(1.0, t / 0.06, (dur - t) / 0.09)
        jitter = 0.75 + 0.25 * math.sin(i * 1.7 + seed * 3.1)
        env.append(round(max(0.0, min(1.0, syl * pause * edge * jitter)), 3))
    return env


def make_stub(out_path):
    """Write a stub timeline mirroring SPEC §6 target times (synthetic envelopes)."""
    starts, acc = {}, 0.0
    scenes_out = []
    for sid, name, dur in _STUB_SCENES:
        starts[sid] = acc
        scenes_out.append({"id": sid, "name": name, "start": acc, "duration": dur})
        acc += dur
    lines_out = []
    for k, (lid, sid, spk, text, st, cap, vo) in enumerate(_STUB_LINES):
        dur = round(0.35 + 0.075 * len(text), 2)
        if lid == "s1_l1":
            dur = 0.82
        en = round(st + dur, 3)
        lines_out.append({
            "id": lid, "scene": sid, "speaker": spk, "text": text, "start": st, "end": en,
            "global_start": round(starts[sid] + st, 3), "global_end": round(starts[sid] + en, 3),
            "wav": f"film/assets/dialogue/{lid}.wav", "caption": cap, "vo": vo, "fx": None,
            "env": _synthetic_env(text, dur, seed=k),
        })
    beats_out = [{"id": b, "scene": s, "t": t, "end": e} for b, s, t, e in _STUB_BEATS]
    data = {"fps": 24, "width": 1920, "height": 1080, "total": acc, "stub": True,
            "cast": {s: {"voice": "stub"} for s in ("MAN", "PHARMACIST", "PHONE", "BOUNCER", "CROWD", "OLD_WOMAN")},
            "scenes": scenes_out, "lines": lines_out, "beats": beats_out}
    out_path = Path(out_path)
    if out_path.resolve() == DEFAULT_PATH.resolve():
        raise ValueError("refusing to overwrite film/timeline.json with a stub")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(data, f, indent=1, ensure_ascii=False)
    return out_path


