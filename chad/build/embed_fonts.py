#!/usr/bin/env python3
"""Embed the title/subtitle fonts as data URIs (web/js/fonts.js) so the player
renders the same type from file://, inside the Artifact sandbox and headless."""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS = {"fredoka": "fredoka-latin.woff2", "luckiest": "luckiest-guy-latin.woff2"}

out = ["// Generated by build/embed_fonts.py from assets/fonts (OFL / Apache-2.0).", "window.FLEECED_FONTS = {"]
for key, name in FONTS.items():
    b64 = base64.b64encode((ROOT / "assets" / "fonts" / name).read_bytes()).decode()
    out.append(f'  {key}: "data:font/woff2;base64,{b64}",')
out.append("};")
(ROOT / "web" / "js" / "fonts.js").write_text("\n".join(out) + "\n")
print("wrote web/js/fonts.js")
